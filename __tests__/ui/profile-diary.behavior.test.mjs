import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { mountProfileDiary } from '../../js/core/profile-diary.mjs';

test('diary opens from the garden, preserves one live frame on close, restores focus and flushes before another profile', async () => {
  const dom = new JSDOM('<main><div data-pc-diary-host></div></main>',{url:'https://example.test/ggulggul/'});
  const {window}=dom, doc=window.document;
  window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  window.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new window.Event('close'));};
  const host=doc.querySelector('[data-pc-diary-host]'), controller=new window.AbortController();
  mountProfileDiary(host,{profileId:'one',signal:controller.signal});
  host.querySelector('button').click();
  const book=doc.querySelector('dialog'), frame=book.querySelector('iframe');
  assert.ok(book.open); assert.equal(new URL(frame.src).pathname,'/diary/');
  window.dispatchEvent(new window.MessageEvent('message',{origin:'https://other.test',source:frame.contentWindow,data:{type:'cd:diary-ready'}}));
  assert.equal(book.dataset.state,'loading');
  window.dispatchEvent(new window.MessageEvent('message',{origin:window.location.origin,source:window,data:{type:'cd:diary-ready'}}));
  assert.equal(book.dataset.state,'loading');
  window.dispatchEvent(new window.MessageEvent('message',{origin:window.location.origin,source:frame.contentWindow,data:{type:'cd:diary-ready'}}));
  assert.equal(book.dataset.state,'ready');
  let visits=0;frame.contentWindow.addEventListener('cd:diary-open',()=>visits++);
  book.querySelector('[data-diary-close]').click();
  assert.equal(doc.activeElement,host.querySelector('button'));
  host.querySelector('button').click();
  assert.equal(book.querySelector('iframe'),frame); assert.equal(doc.querySelectorAll('dialog').length,1);
  assert.equal(visits,1,'same-profile reopening refreshes the existing diary controller');
  window.dispatchEvent(new window.MessageEvent('message',{origin:'https://other.test',source:frame.contentWindow,data:{type:'cd:diary-close'}}));
  assert.equal(book.open,true);
  window.dispatchEvent(new window.MessageEvent('message',{origin:window.location.origin,source:frame.contentWindow,data:{type:'cd:diary-close'}}));
  assert.equal(book.open,false);
  host.querySelector('button').click();
  controller.abort(); await Promise.resolve(); assert.equal(book.open,false);
  let flushed=0; frame.contentWindow.addEventListener('cd:diary-flush',()=>flushed++);
  const second=new window.AbortController();
  mountProfileDiary(host,{profileId:'two',signal:second.signal});
  host.querySelector('button').click();
  assert.equal(flushed,1); assert.equal(frame.dataset.profileId,'two');
  assert.equal(doc.querySelectorAll('iframe').length,1);
  second.abort(); dom.window.close();
});
