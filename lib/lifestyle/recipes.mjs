export const recipePath = (recipe) => `/recipes/${recipe.slug}/`;
export const recipeImage = (recipe) => `/images/five-elements/${recipe.image}-2d.webp`;
export function recipeStageImage(recipe, index) {
  const stage = recipe.stages[index];
  if (recipe.host === '영냥이' && stage === 'chef') return recipeImage(recipe);
  const character = recipe.host === '영냥이' ? 'yeongnyangi' : 'yeoni';
  return `/images/five-elements/${character}-${stage}-2d.webp`;
}

export function recipeJsonLd(recipe, origin) {
  return {
    '@context': 'https://schema.org', '@type': 'Recipe', name: recipe.name,
    description: recipe.description, image: `${origin}${recipeImage(recipe)}`,
    url: `${origin}${recipePath(recipe)}`, author: { '@type': 'Organization', name: 'CODE DESTINY' },
    recipeYield: '2', prepTime: `PT${recipe.prep}M`, cookTime: `PT${recipe.cook}M`, totalTime: `PT${recipe.prep + recipe.cook}M`,
    recipeIngredient: recipe.ingredients,
    recipeInstructions: recipe.steps.map(([name, text], i) => ({ '@type': 'HowToStep', name, text, url: `${origin}${recipePath(recipe)}#step-${i + 1}` })),
  };
}
