export function calcRelationType(myIdx: number, targetIdx: number) {
  const diff = Math.abs(myIdx - targetIdx) % 27;
  return (
    RELATION_TYPES.find((r) => r.diff === diff) ?? {
      rel: "중성(中)",
      desc: "비교적 중립적인 관계입니다.",
    }
  );
}

