export const PROMPT_HUB_TOOL_IDS = Object.freeze(Object.keys(PROMPT_HUB_TOOLS));

/**
 * fields: 화면 순서대로의 [{ id, label, value }] (value 는 클라이언트 formatDraftValue 결과).
 * computedFacts: 사용자의 입력으로 클라이언트가 산출한 [산출 데이터] 블록.
 */
export function buildStructuredFortunePrompt(toolId, fields = [], computedFacts = "") {
  const config = PROMPT_HUB_TOOLS[toolId];
  if (!config) throw new Error("UNKNOWN_PROMPT_HUB_TOOL");
  const valueOf = (id) => String(fields.find((field) => field.id === id)?.value || "").trim();
  const filledFields = fields
    .map((field) => {
      const value = String(field.value || "").trim();
      return value ? `- ${field.label}: ${value}` : "";
    })
    .filter(Boolean)
    .join("\n");
  const avoid = valueOf("avoid");
  const tone = valueOf("tone") || "차분하고 전문적인 상담";
  const depth = valueOf("depth") || "균형 있게";
  const selectedSystems = valueOf("systems");
  const facts = String(computedFacts || "").trim();

  return [
    `당신은 ${config.role}입니다.`,
    "",
    `선택된 운세 체계: ${selectedSystems || config.label}`,
    `해석 모티프: ${config.motif}`,
    `상담 분위기: ${tone}`,
    `답변 깊이: ${depth}`,
    "",
    "[입력 단서]",
    filledFields || "- 아직 입력된 단서가 적습니다. 부족한 정보는 추정하지 말고 필요한 확인 질문을 먼저 제안해 주세요.",
    avoid ? `\n피해야 할 표현: ${avoid}` : "",
    facts ? `\n${facts}` : "",
    "",
    "[해석 원칙]",
    ...config.principles.map((item) => `- ${item}`),
    facts
      ? "- 위 [산출 데이터]의 명칭·수치·관계는 이미 확정된 값이니 그대로 근거로 삼고, 임의로 바꾸거나 새로 계산하지 않습니다."
      : "",
    "- 입력 단서에 없는 값(생년월일시, 명식, 별자리 등)은 지어내지 말고, 필요하면 계산이 필요하다고 표시하거나 확인 질문을 제안합니다.",
    "- 단정적인 예언, 공포를 주는 표현, 운명을 고정하는 표현은 피합니다.",
    "- 불확실한 내용은 가능성, 경향, 선택지의 언어로 설명합니다.",
    "- 의료, 법률, 투자, 계약 등 전문 판단을 대신하지 않으며 필요한 경우 전문가 상담을 권합니다.",
    "- 질문자가 오늘 실천할 수 있는 현실적인 조언을 포함합니다.",
    "",
    "[답변 구조]",
    ...config.answerSections.map((item, index) => `${index + 1}. ${item}`),
    "",
    "[말투]",
    "전문적이되 차갑지 않게, 신비롭되 과장하지 않게 말해 주세요. 운세의 상징은 질문자가 자기 선택을 더 선명하게 바라보도록 돕는 언어로 전해 주세요.",
  ]
    .filter(Boolean)
    .join("\n");
}
