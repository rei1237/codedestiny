/**
 * 원고가 있는 인물(초안 포함). 표시용.
 * @param {string} slug
 * @returns {CelebrityEditorialEntry | null}
 */
export function getCelebrityEditorial(slug) {
  return Object.prototype.hasOwnProperty.call(CELEBRITY_EDITORIAL, slug) ? CELEBRITY_EDITORIAL[slug] : null;
}

/** 검수가 끝나 색인·사이트맵에 올리는 인물만. 🔴 색인 여부를 정하는 함수는 이것 하나다. */
export function getIndexedCelebrityEditorial(slug) {
  const entry = getCelebrityEditorial(slug);
  return entry && entry.reviewedAt ? entry : null;
}

/** @returns {string[]} */
export function getIndexedCelebritySlugs() {
  return Object.keys(CELEBRITY_EDITORIAL).filter((slug) => Boolean(CELEBRITY_EDITORIAL[slug].reviewedAt));
}
