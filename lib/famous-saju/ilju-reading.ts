export function getIljuReading(name: string) {
  const cycle = ILJU.find(x => x.name === name);
  if (!cycle) return null;
  const stem = stems[STEMS.indexOf(cycle.stem)], branch = branches[BRANCHES.indexOf(name[1])];
  return { ...cycle, title:`${branch[0]}에 놓인 ${stem[0]}`, stemReading:stem[1], question:stem[2], branchReading:branch[2], hiddenStems:branch[1] };
}
