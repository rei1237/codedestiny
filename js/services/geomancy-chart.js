const findFig=r=>{const k=r.join('');return Object.values(FIG).find(f=>f.r.join('')===k)||null;};
const addF=(a,b)=>a.map((v,i)=>(v+b[i])%2);
const mkF=r=>r.map(v=>v%2===1?1:0);
function fromCounts(counts){
  const bits=counts.map(n=>n%2);
  const m=[0,1,2,3].map(mi=>mkF([bits[mi*4],bits[mi*4+1],bits[mi*4+2],bits[mi*4+3]]));
  const d=[0,1,2,3].map(di=>mkF(m.map(mm=>mm[di])));
  const n=[addF(m[0],m[1]),addF(m[2],m[3]),addF(d[0],d[1]),addF(d[2],d[3])];
  const w=[addF(n[0],n[1]),addF(n[2],n[3])];
  return{mothers:m,daughters:d,nephews:n,witnesses:w,judge:addF(w[0],w[1])};
}
function toOracleCardPayload(fd,t,roleName){
  if(!fd)return null;
  const isAlch=t==='alchemist';
  const tone=fd[isAlch?'al':'su']||{};
  return {
    role:roleName,
    english:fd.en||'',
    korean:fd.nm||'',
    symbol:fd.sig||'',
    element:fd.el||'',
    meaning:String(tone.m||''),
    advice:String(tone.a||''),
  };
}
