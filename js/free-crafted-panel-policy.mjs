export function currentFreeCraftedPanel(detail, panel) {
 if (!isFreeFortuneFeatureKey(detail?.featureKey)) return panel;
 let text = String(panel.text || '');
 for (const [oldText, newText] of replacements) text = text.split(oldText).join(newText);
 if (text === panel.text) return panel;
 return { ...panel, text: text.replace(/\n{3,}/g, '\n\n').trim(), currentFreeAccess: true };
}
