export const FOLLOWUP_SOLUTION_MARKER = "[추가 질문 해결 계약]";
export const FOLLOWUP_EMPATHY_MARKER = "[운세 근거 공감 계약]";

export function followupSolutionPromptLines({ feature = "추가 상담", empathy = "warm", openingOwner = true } = {}) {
  const empathyLines = openingOwner ? [
    FOLLOWUP_EMPATHY_MARKER,
    empathy === "tactical"
      ? "- 첫 문단의 1~2문장에서 사용자가 새로 밝힌 현실과 저장된 운세 근거 하나를 함께 짚어, 그 반응이 생긴 이유를 전술적으로 인정한다. 부드러운 위로나 긴 워밍업 없이 바로 판세 판단으로 전환한다."
      : "- 첫 문단의 1~2문장에서 사용자가 새로 밝힌 현실이나 감정과 저장된 운세 근거 하나를 함께 짚어, 왜 그런 반응이 생길 수 있는지 구체적으로 공감한다.",
    "- '많이 힘드셨겠어요' 같은 범용 공감만 쓰지 않는다. 사용자가 말하지 않은 감정·사건·상대 속마음을 공감이라는 이름으로 지어내거나 결과를 보장하지 않는다.",
    "- 공감에 쓰는 운세 근거는 현재 상담 체계의 저장된 계산값과 source id에서만 고른다. 사주·자미두수·서양 점성술·베다점·숙요점·타로의 용어와 계산 체계를 서로 섞지 않는다.",
    "- 기존 출력 스키마에 empathy 필드가 있으면 공감을 그 필드에, 없으면 첫 본문 필드의 첫 문단에 쓴다. 형식 때문에 핵심 답변을 생략하거나 유효한 상담 전체를 버리지 않는다.",
  ] : [
    "[공감 반복 금지]",
    "- 이 부분은 첫 공감 문단의 소유자가 아니다. 앞부분의 공감을 다시 쓰지 말고 이 부분이 맡은 판단·행동·대안만 새롭게 설명한다.",
  ];
  return [
    FOLLOWUP_SOLUTION_MARKER,
    `- ${feature}에서는 이전 결과 전체를 다시 요약하지 않는다. ${openingOwner ? "짧은 근거 공감 직후" : "담당 내용의 첫 문장부터"} 사용자가 방금 묻거나 새로 알려준 사실에 직접 답하고, 이전 결론은 비교에 필요한 한 줄만 가져온다.`,
    ...empathyLines,
    "- 답하기 전에 내부적으로 '새로 들어온 사실 / 그대로인 조건 / 지금 답해야 할 결정'을 구분한다. 이 내부 분류명은 출력하지 않는다.",
    "- 새 사실이 이전 결론을 바꾸지 않으면 유지되는 이유를, 범위를 좁히면 무엇이 달라졌는지를 밝힌다. 이전 결론과 달라지면 조용히 뒤집지 말고 어떤 새 조건 때문에 수정되는지 설명한다.",
    "- 저장된 계산 근거와 사용자가 실제로 말한 내용만 사용한다. 새 차트·카드·시기 계산, 상대의 속마음, 과거 사건, 실행 결과를 지어내지 않는다.",
    `- ${openingOwner ? "근거 공감 → " : ""}직접 답 → 판단 근거와 성립 조건 → 가장 권하는 행동 하나 → 여건이 안 될 때의 대안 하나 → 멈추거나 다시 판단할 관찰 신호 순서로 해결한다. 기존 스키마가 있으면 해당 내용을 기존 필드에 나누어 담는다.`,
    "- 여러 선택지가 있어도 나열로 끝내지 않는다. 지금 조건에서 우선할 한 가지를 고르고, 예상되는 비용·불편·포기할 것을 짧게 밝혀 사용자가 선택할 수 있게 한다.",
    "- 행동은 대상·시점·횟수나 범위·확인할 반응 중 가능한 요소를 붙여 실제로 실행할 수 있게 쓴다. '기다려라', '노력해라', '대화해라'처럼 기준 없는 동사만 제시하지 않는다.",
    "- 근거가 부족해 확답할 수 없으면 아는 범위의 답과 한계를 먼저 주고, 현실에서 확인할 정보 하나만 요청한다. 기본 답을 일부러 남겨 두거나 추가 결제를 해결책처럼 권하지 않는다.",
    "- 안전·건강·법률·투자처럼 운세 근거만으로 결정하면 위험한 사안은 운세의 한계를 밝히고 검증 가능한 현실 기준과 전문 도움을 함께 안내한다.",
  ];
}

export function followupSolutionPromptText(options = {}) {
  return followupSolutionPromptLines(options).join("\n");
}
