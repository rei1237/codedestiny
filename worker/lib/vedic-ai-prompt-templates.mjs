export function getVedicPromptTemplate(domain) {
  return applyPromptTemplateOverride("vedic", domain, VEDIC_PROMPT_TEMPLATES[domain] || null);
}

/**
 * 모든 도메인 리스트 반환
 */
export function getAvailableVedicDomains() {
  return Object.keys(VEDIC_PROMPT_TEMPLATES).map((key) => ({
    key,
    ko: VEDIC_PROMPT_TEMPLATES[key].domainKo,
    title: VEDIC_PROMPT_TEMPLATES[key].title,
  }));
}

/**
 * 질문을 통해 적절한 도메인 자동 분류
 */
export function classifyQuestionToVedicDomain(question) {
  const text = String(question || "").toLowerCase();

  const domainKeywords = {
    litigation: ["송사", "재판", "법", "분쟁", "고소", "변호사", "법정", "판사", "소송", "법률"],
    romance: ["연애", "결혼", "남녀", "사귀", "썸", "이별", "배우자", "부부", "관계", "궁합"],
    wealth: ["돈", "재물", "투자", "사업", "창업", "수입", "자산", "부", "경제", "재정"],
    relationships: ["인간관계", "가족", "친구", "직장", "동료", "소통", "갈등", "친분", "관계"],
    health: ["건강", "질병", "스트레스", "불안", "차크라", "도샤", "웰니스", "명상", "요가", "힐링"],
    career: ["직업", "이직", "승진", "커리어", "창업", "진로", "회사", "조직", "리더십", "경력"],
    spirituality: ["영성", "명상", "깨달음", "카르마", "영적", "신앙", "요가", "낙샤트라", "영혼", "목적"],
  };

  for (const [domain, keywords] of Object.entries(domainKeywords)) {
    if (keywords.some((kw) => text.includes(kw))) {
      return domain;
    }
  }

  return "spirituality"; // 기본값
}
