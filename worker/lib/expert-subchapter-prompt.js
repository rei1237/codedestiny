export const EXPERT_SUBCHAPTER_MARKER = "[전문가 소단락 설계 계약]";

export function expertSubchapterPromptLines({ feature = "전문가 상담", schemaMode = "text", compact = false } = {}) {
  if (compact) return [
    EXPERT_SUBCHAPTER_MARKER,
    `- ${feature}의 장 ID·제목·순서·개수와 JSON 필드를 유지한다. 근거와 질문에 따라 장 안에 2~6개 소단락을 유동적으로 설계하되 근거가 적으면 합친다.`,
    "- 소단락마다 다른 질문 하나에 실제 근거와 생활 조건, 선택 기준을 연결한다. 구체적인 제목을 쓰고 같은 근거·결론이나 첫 장의 성향을 반복하지 않는다.",
    "- 제공되지 않은 사건·감정·직업·상대 마음·시기는 만들지 않는다. 근거가 부족하면 한계를 밝히고, 새 정보가 없는 문단은 합친다.",
    schemaMode === "metadata"
      ? "- 내부 계획은 출력하지 않는다. 기존 subchapters 범위가 본문을 중복·누락 없이 가리키게 한다."
      : "- 내부 계획은 출력하지 않는다. 별도 필드 없이 기존 본문의 소제목과 문단으로 구분한다.",
  ];
  return [
    EXPERT_SUBCHAPTER_MARKER,
    `- ${feature}의 상위 장 ID·제목·순서·개수와 기존 JSON 필드는 그대로 유지한다. 상위 장을 합치거나 삭제하거나 다른 장의 책임 범위를 가져오지 않는다.`,
    "- 각 상위 장 안에서만 근거 밀도와 사용자 질문에 따라 2~6개의 소단락을 유동적으로 설계한다. 근거가 적거나 질문이 단순하면 1~2개로 합치고, 서로 다른 판단과 근거가 충분할 때만 5~6개까지 나눈다.",
    "- 소단락 하나는 하나의 판단만 맡는다: 답하려는 질문 1개 → 실제 계산 근거 1~3개 → 생활에서 확인할 장면이나 조건 → 선택 또는 확인 기준. 같은 근거와 결론을 다른 소단락에서 다시 설명하지 않는다.",
    "- 첫 성향 장이 맡은 타고난 기질은 뒤 장에서 다시 정의하지 않는다. 뒤 장은 그 기질이 연애·일·돈·관계·시기 중 이번 장의 주제에서 어떻게 작동하는지만 한 줄로 연결하고 새 근거로 진행한다.",
    "- 장을 나누기 전에 내부적으로 '이번 장이 새로 답할 것 / 사용할 근거 / 다른 장에 남길 것'을 정한다. 출력에는 이 내부 계획이나 시스템 용어를 노출하지 않는다.",
    "- 소단락 제목은 '근거', '분석', '조언' 같은 범용어 대신 사용자가 궁금해할 구체적인 결론이나 장면을 담는다. 제목만 바꾸고 같은 본문을 반복하지 않는다.",
    "- 분량보다 정확도가 우선이다. 근거가 부족하면 소단락 수를 줄이고 한계를 해당 판단 옆에 밝힌다. 소단락 수를 맞추려고 사건·감정·직업·상대 마음·시기를 만들지 않는다.",
    "- 문단마다 앞 문단에 없던 새 정보가 있어야 한다. 새 근거, 반대 신호, 성립 조건, 생활 장면, 행동 또는 확인 기준 중 하나도 새롭지 않으면 그 문단을 삭제하거나 합친다.",
    schemaMode === "metadata"
      ? "- 기존 subchapters 메타데이터가 있으면 실제 본문의 문단 범위를 중복·누락 없이 가리키게 하고, 본문을 메타데이터에 복사하지 않는다."
      : "- 별도 subchapters 필드가 없는 스키마에서는 content/body의 짧은 소제목과 문단 묶음으로만 구분한다. JSON 필드를 새로 만들지 않는다.",
  ];
}

export function expertSubchapterPromptText(options = {}) {
  return expertSubchapterPromptLines(options).join("\n");
}

