const MARKER = "[타고난 성향 정확도 계약]";

function normalizeType(fortuneType, fortuneLabel = "") {
  const type = String(fortuneType || "").trim().toLowerCase();
  const label = String(fortuneLabel || "");
  if (type === "saju" || label.includes("사주")) return "saju";
  if (type === "ziwei" || label.includes("자미")) return "ziwei";
  if (["sukyo", "sukuyo"].includes(type) || label.includes("숙요")) return "sukuyo";
  if (type === "vedic" || label.includes("베다")) return "vedic";
  if (type === "astrology" || (label.includes("점성술") && !label.includes("베다"))) return "astrology";
  return "";
}

