/** 81수리 분류. 프롬프트 검증·테스트에서 쓴다. */
export function suriFortune(number) {
  const value = Math.floor(Number(number) || 0);
  if (value < 1) return "unknown";
  // 81을 넘으면 81을 빼고 다시 본다(전통 규칙).
  const normalized = value > 81 ? ((value - 1) % 81) + 1 : value;
  if (AUSPICIOUS.indexOf(normalized) >= 0) return "auspicious";
  if (HALF.indexOf(normalized) >= 0) return "half";
  if (INAUSPICIOUS.indexOf(normalized) >= 0) return "inauspicious";
  return "unknown";
}

