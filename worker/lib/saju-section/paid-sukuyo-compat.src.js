// input: { myMoonEclipticLongitude, partnerMoonEclipticLongitude, partnerGender:'M'|'F'|'OTHER', userGender:'M'|'F' }
function renderSukuyoCompatPaid(input) {
  var sData = calcSukuyoData({ moonEclipticLongitude: input.myMoonEclipticLongitude });
  var tData = calcSukuyoData({ moonEclipticLongitude: input.partnerMoonEclipticLongitude });
  if (!sData || !tData) return null;
  var report = syBuildSukuyoCompatReport(sData.mansionIdx, sData.mansion, tData, input.partnerGender, input.userGender);
  report.myMansion = sData.mansion;
  report.myMansionIdx = sData.mansionIdx;
  report.partnerMansion = tData.mansion;
  report.partnerMansionIdx = tData.mansionIdx;
  return report;
}
