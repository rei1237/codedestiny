function describeSoulOriginTerms(terms = []) {
  const seen = new Set();
  return (Array.isArray(terms) ? terms : [])
    .map((term) => clean(term))
    .filter(Boolean)
    .filter((term) => {
      if (seen.has(term)) return false;
      seen.add(term);
      return true;
    })
    .slice(0, 4)
    .map((term) => `${term}: ${SOUL_ORIGIN_TERM_BRIEFS[term] || "이 항목의 반복을 읽는 핵심 신호"}`)
    .join(" / ");
}

