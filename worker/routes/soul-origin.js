function validateSoulOriginSectionAccuracy(section = {}, chapterId = "", sectionIndex = 0, expectedTitle = "") {
  const body = stripForbiddenTokens(section?.body || "");
  const profile = getSoulOriginSectionCounsel(chapterId, sectionIndex, expectedTitle);
  const errors = [];
  const hasProfileText = (value) => {
    const expected = stripForbiddenTokens(value);
    return !expected || body.includes(expected);
  };
  if (clean(expectedTitle) && !body.includes(clean(expectedTitle))) errors.push("category_title_missing");
  if (profile.requiredTerms.length && countSoulOriginHits(body, profile.requiredTerms) < Math.min(2, profile.requiredTerms.length)) errors.push("category_terms_missing");
  if (profile.focus && !hasProfileText(profile.focus)) errors.push("category_focus_missing");
  if (profile.evidence && !hasProfileText(profile.evidence)) errors.push("category_evidence_missing");
  if (profile.strategy && !hasProfileText(profile.strategy)) errors.push("category_strategy_missing");
  if (profile.practice && !hasProfileText(profile.practice)) errors.push("category_practice_missing");
  if (!body.includes("고수의 판정")) errors.push("master_verdict_missing");
  if (!body.includes("교차 판정")) errors.push("master_cross_evidence_missing");
  if (!body.includes("해방 처방")) errors.push("master_remedy_missing");
  if (countSoulOriginHits(body, ["명리 고수", "자미두수 고수", "점성술 고수", "베다점 고수", "숙요점 고수"]) < 3) errors.push("master_panel_missing");
  if (countSoulOriginHits(body, ["전용 진단", "같은 장의 다른 항목", "실제로 어디서 흔들리는지"]) < 1) errors.push("category_specific_brief_missing");
  if (countSoulOriginHits(body, ["현실의 언어", "이 신호", "고요히 드러납니다", "조언으로 내려옵니다"]) < 1) errors.push("term_translation_missing");
  return errors;
}

function validateSoulOriginGeneratedChapter(chapter = {}, blueprint = {}) {
  const expected = CHAPTER_BLUEPRINTS.find((item) => String(item.id) === String(blueprint?.id || chapter?.id || "")) || blueprint || {};
  const expectedTitles = Array.isArray(expected.categories) ? expected.categories : [];
  const sections = Array.isArray(chapter?.sections) ? chapter.sections : [];

  if (clean(chapter?.id) !== clean(expected.id)) {
    return { ok: false, errors: [`chapter_${clean(chapter?.id || "")}_title`] };
  }
  if (clean(chapter?.title || "") !== clean(expected.title || "")) {
    return { ok: false, errors: ["chapter_title_mismatch"] };
  }
  if (sections.length !== expectedTitles.length) {
    return { ok: false, errors: ["chapter_section_count"] };
  }
  if (clean(chapter?.subtitle || "") !== clean(expected.subtitle || "")) {
    return { ok: false, errors: ["chapter_subtitle_mismatch"] };
  }

  const errors = [];
  let chapterChars = 0;
  sections.forEach((section, index) => {
    const expectedTitle = clean(expectedTitles[index] || "");
    const title = clean(section?.title || "");
    const body = stripForbiddenTokens(section?.body || "");
    if (expectedTitle && title !== expectedTitle) {
      errors.push(`chapter_${expected.id}_section_${index + 1}_title`);
    }
    if (body.length < MIN_CATEGORY_CHARS) {
      errors.push(`chapter_${expected.id}_section_${index + 1}_short`);
    }
    if (hasForbiddenText(body)) {
      errors.push(`chapter_${expected.id}_section_${index + 1}_forbidden`);
    }
    SECTION_TITLES.forEach((heading) => {
      if (!body.includes(heading)) {
        errors.push(`chapter_${expected.id}_section_${index + 1}_heading_missing`);
      }
    });
    validateSoulOriginSectionAccuracy(section, expected.id, index, expectedTitle).forEach((issue) => {
      errors.push(`chapter_${expected.id}_section_${index + 1}_${issue}`);
    });
    chapterChars += body.length;
  });

  if (chapterChars < MIN_CHAPTER_CHARS) {
    errors.push(`chapter_${expected.id}_total_short`);
  }

  return {
    ok: errors.length === 0,
    errors,
    totalChars: sections.reduce((sum, section) => sum + stripForbiddenTokens(section?.body || "").length, 0),
  };
}

function validateSoulOriginSummary(summary = "") {
  const text = stripForbiddenTokens(summary);
  const errors = [];
  if (text.length < 120) errors.push("summary_short");
  if (text.length > 700) errors.push("summary_long");
  if (hasForbiddenText(text)) errors.push("summary_forbidden");
  return { ok: errors.length === 0, errors, summary: text };
}

