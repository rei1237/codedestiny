// Reuse canonical generated line art without importing the web shell's selectors.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../../../',import.meta.url);
const families=[['styles/yehwa-motifs.css',['--cd-yehwa-mask-branch-corner','--cd-yehwa-mask-seal']],['app/yeongnyangi/yehwa-night.generated.css',['--yn-yehwa-mask-branch-spray']]];
const declarations=[];
for(const [source,names] of families){
  const css=fs.readFileSync(new URL(source,root),'utf8');
  for(const name of names){
    const value=css.match(new RegExp(`${name}:\\s*(url\\("[^"\\n]+"\\))\\s*;`))?.[1];
    if(!value)throw new Error(`Missing canonical motif: ${name}`);
    declarations.push(`  ${name}: ${value};`);
  }
}
const target=fileURLToPath(new URL('../src/yehwa-motifs.generated.css',import.meta.url));
const output='/* Generated by apps/toss/scripts/sync-yehwa-motifs.mjs. Do not hand-edit paths. */\n:root{\n'+declarations.join('\n')+'\n}\n';
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8')!==output)throw new Error('Toss motifs differ from canonical artwork');
}else fs.writeFileSync(target,output);
