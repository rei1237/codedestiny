import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const origin='http://127.0.0.1:'+Number(process.env.TOSS_TEST_PORT||4329);
const browser=await chromium.launch({channel:'chrome'});
const context=await browser.newContext({viewport:{width:360,height:740},isMobile:true,serviceWorkers:'block'});
context.setDefaultTimeout(90000);
await context.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
const home=async p=>{await p.goto(origin);await p.locator('.world-entry-ggulggul').click();};
const enter=async p=>{await home(p);await p.getByRole('button',{name:'흑월의 경고 상담'}).click();};
try{
  const page=await context.newPage();
  page.on('pageerror',error=>console.error(error.message));
  await enter(page);
  await page.getByRole('link',{name:'토스로 로그인하기'}).click();
  await page.getByRole('button',{name:'토스로 로그인하기'}).click();
  await page.getByRole('button',{name:'새 프로필 만들기'}).click();
  const form=page.locator('form').filter({has:page.locator('input[name=name]')});
  await form.locator('input[name=name]').fill('모의 생시');
  await form.locator('input[name=date]').fill('19900101');
  await form.getByPlaceholder('08:35').fill('0835');
  await form.locator('button[type=submit]').click();
  await form.waitFor({state:'hidden'});
  await page.getByLabel('어떤 일을 겪었고, 무엇이 걱정되나요?').fill('이직을 고민하면서 올해 조심할 일을 알고 싶어요.');
  await page.getByRole('button',{name:'상담 시작하기'}).click();
  await page.waitForURL(/heukwol\/\?result=/);
  const resultUrl=page.url();
  await page.close();
  const reopen=await context.newPage();
  await home(reopen);
  await reopen.getByRole('link',{name:'꿀꿀운세 구매 기록'}).click();
  await reopen.locator('article').filter({hasText:'이직을 고민하면서'}).getByRole('link').last().click();
  const text='[테스트 전용] 흑월의 저장된 상담 원문입니다.';
  await reopen.getByText(text,{exact:true}).first().waitFor();
  assert.equal(reopen.url(),resultUrl);
  await reopen.reload();
  await reopen.getByText(text,{exact:true}).first().waitFor();
  assert.deepEqual(await reopen.evaluate(()=>{const s=JSON.parse(localStorage.getItem('toss-offline-fixture'));return [s.orders.length,s.intents.length,s.intents[0][1].generationCount];}),[1,1,1]);
  await reopen.goto(origin);
  await reopen.getByRole('button',{name:'내 정보',exact:true}).click();
  await reopen.getByRole('button',{name:'로그아웃',exact:true}).click();
  await reopen.getByText('로그아웃했어요.').waitFor();
  await reopen.evaluate(()=>localStorage.setItem('toss-offline-login-person','second'));
  await enter(reopen);
  await reopen.getByRole('link',{name:'토스로 로그인하기'}).click();
  await reopen.getByRole('button',{name:'토스로 로그인하기'}).click();
  await reopen.getByRole('button',{name:'새 프로필 만들기'}).waitFor();
  assert.equal(await reopen.evaluate(()=>JSON.parse(localStorage.getItem('toss-offline-fixture-2')).loggedIn),true);
  await reopen.goto(resultUrl);
  await reopen.getByRole('heading',{name:'구매 기록 확인'}).waitFor();
  await reopen.waitForLoadState('networkidle');
  assert.equal(await reopen.getByText(text,{exact:true}).count(),0);
  console.log('PASS 흑월 홈 → 로그인·출생 시각 입력·질문 → 가상 결제 → 진행 중 닫기 → 구매 기록 → 원문 재열람');
}finally{await browser.close();}
