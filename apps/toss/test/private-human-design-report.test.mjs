import '../../../scripts/lib/mock-network-guard.cjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {createSimulationApi} from '../private-simulation/api.mjs';
import {buildHumanDesignReportPlan} from '../../../lib/human-design/report-plan.js';
import {ownsReviewReceipt} from '../src/review-scope.mjs';
const stores={A:new Map(),B:new Map()};
const storage=person=>({getItem:key=>stores[person].get(key),setItem:(key,value)=>stores[person].set(key,value)});
const apis={A:createSimulationApi(storage('A'),'A'),B:createSimulationApi(storage('B'),'B')};
const call=(person,path,body)=>apis[person](new Request('https://mock.invalid/private-simulation-api'+path,{method:body===undefined?'GET':'POST',headers:{Authorization:'Bearer private-simulation-token-'+person},...(body===undefined?{}:{body:JSON.stringify(body)})}));
test('18-chapter simulation preserves one order, immutable input and owned saved original after restart',async()=>{
 const input={requestId:'human-design-00000000-0000-4000-8000-000000000000',birth:{birthDate:'1990-01-01',birthTime:'08:35',timezone:'Asia/Seoul',calendar:'solar'},locale:'ko'};
 assert.equal((await call('A','/native/human-design/prepare',{input})).status,401);
 for(const person of ['A','B'])await call(person,'/login',{authorizationCode:'private-simulation-person-'+person});
 const row=await (await call('A','/native/human-design/prepare',{input})).json();assert.ok(row.id);
 assert.equal((await (await call('A','/native/human-design/prepare',{input})).json()).id,row.id);
 assert.equal((await call('A','/native/human-design/prepare',{input:{...input,birth:{...input.birth,birthTime:'09:00'}}})).status,409);
 const path='/native/human-design/results/'+row.id;
 assert.equal((await call('A',path,{})).status,402);
 const order={requestId:row.id,sku:row.sku,orderId:'private-order-A-hd'};
 assert.equal((await call('A','/orders/grant',{...order,orderId:'private-order-B-hd'})).status,403);
 assert.equal((await call('A','/orders/grant',{...order,sku:'real-console-sku'})).status,403);
 assert.equal((await call('A','/orders/grant',order)).status,200);
 assert.equal((await call('A','/orders/grant',order)).status,200);
 assert.equal((await call('A',path)).status,202);
 apis.A=createSimulationApi(storage('A'),'A');
 const original=await (await call('A',path,{})).json();
 assert.equal(original.sections.length,18);assert.match(original.sections[0].body,/모의 결과/);
 assert.equal(buildHumanDesignReportPlan(original,original.chart).chapters.length,18);
 apis.A=createSimulationApi(storage('A'),'A');
 assert.deepEqual(await (await call('A',path)).json(),original);
 assert.deepEqual(await (await call('A',path,{})).json(),original);
 assert.equal((await call('B',path)).status,404);
 assert.equal((await call('B','/orders/restore',order)).status,403);
 const records=await (await call('A','/canonical/records')).json();assert.ok(records.items.some(item=>item.href==='/human-design/report/?intentId='+row.id));
 assert.equal(await ownsReviewReceipt('/human-design/report/?intentId='+row.id,async()=>await (await call('A','/library')).json()),true);
 assert.equal(await ownsReviewReceipt('/human-design/report/?intentId='+row.id,async()=>await (await call('B','/library')).json()),false);
 assert.equal((await (await call('B','/canonical/records')).json()).items.length,0);
 const saved=JSON.parse(stores.A.get('consultations'));assert.equal(saved.orders.length,1);assert.equal(saved.intents[0][1].generationCount,1);
});
