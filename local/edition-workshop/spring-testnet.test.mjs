import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir,mkdtemp,readFile,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createHash} from 'node:crypto';
import ganache from 'ganache';
import solc from 'solc';
import {BrowserProvider,ContractFactory} from 'ethers';
import {PNG} from 'pngjs';
import jsQR from 'jsqr';
import {characterQR} from './character-qr.mjs';
import {readSpring,sendSpring,spring} from '../../lib/editions/spring-testnet.mjs';

test('메인넷에서는 지갑 연결이나 서명에 앞서 중단한다',async()=>{
  const methods=[];
  const wallet={request:async({method})=>{methods.push(method);return '0x1';}};
  await assert.rejects(sendSpring(wallet,'seal',30,'0x'+'1'.repeat(40)),/Sepolia/);
  assert.deepEqual(methods,['eth_chainId']);
});
test('실제 계약으로 30개 한도·001번을 대조하고 사진 QR을 판독한다',async t=>{
  const root=fileURLToPath(new URL('.state/',import.meta.url));
  await mkdir(root,{recursive:true});
  const dir=await mkdtemp(path.join(root,'spring-'));
  const chain=ganache.provider({database:{dbPath:dir},chain:{chainId:84532},logging:{quiet:true}});
  const provider=new BrowserProvider(chain,undefined,{cacheTimeout:-1,pollingInterval:30});
  t.after(async()=>{provider.destroy();await chain.disconnect();await rm(dir,{recursive:true,force:true});});
  const source=(await readFile(new URL('Edition.sol',import.meta.url),'utf8')).replace(/\r\n/g,'\n');
  const input={language:'Solidity',sources:{'Edition.sol':{content:source}},settings:{evmVersion:'shanghai',optimizer:{enabled:true,runs:200},outputSelection:{'*':{'*':['abi','evm.bytecode.object']}}}};
  const {abi,evm}=JSON.parse(solc.compile(JSON.stringify(input))).contracts['Edition.sol'].Edition;
  const artifact=JSON.parse(await readFile(new URL('../../public/assets/edition-testnet/edition-deploy.json',import.meta.url),'utf8'));
  assert.equal(artifact.data,'0x'+evm.bytecode.object);
  assert.equal(artifact.chainId,spring.chain);
  const signer=await provider.getSigner(), instance=await new ContractFactory(abi,evm.bytecode.object,signer).deploy();
  await instance.waitForDeployment();
  const contract=await instance.getAddress();
  const rpc=(method,params)=>chain.request({method,params});
  const wallet={request:({method,params})=>rpc(method==='eth_requestAccounts'?'eth_accounts':method,params)};
  const art=await readFile(new URL('../../public/assets/mascot/yeoni-profile-v1.webp',import.meta.url));
  assert.equal(createHash('sha256').update(art).digest('hex'),spring.work);
  const seal=await sendSpring(wallet,'seal',30,contract);
  await assert.rejects(readSpring(seal,rpc,contract),/발행 거래/);
  await assert.rejects(sendSpring(wallet,'seal',31,contract),/한도/);
  const tx=await sendSpring(wallet,'mint',30,contract);
  const proof=await readSpring(tx,rpc,contract);
  assert.deepEqual([proof.cap,proof.issued,proof.serial],[30,1,1]);
  assert.equal(proof.explorer,'https://sepolia.basescan.org/tx/'+tx);
  await assert.rejects(sendSpring(wallet,'mint',30,contract),/발행 상태/);
  const url='https://code-destiny.com/editions/spring/?tx='+tx;
  const image=PNG.sync.read(await characterQR(url,'yeoni',1));
  assert.equal(jsQR(new Uint8ClampedArray(image.data),image.width,image.height)?.data,url);
  await (await instance.mint('0x'+spring.series,2,'0x'+spring.work)).wait();
  assert.equal((await readSpring(tx,rpc,contract)).issued,2);
  await (await instance.invalidate(await instance.number('0x'+spring.series,1),'0x'+spring.work)).wait();
  await assert.rejects(readSpring(tx,rpc,contract),/유효한/);
});
