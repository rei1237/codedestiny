import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { PNG } from 'pngjs';
import jsQR from 'jsqr';
import {mkdir} from 'node:fs/promises';
import path from 'node:path';
const origin=new URL(process.argv[2] || 'http://127.0.0.1:32704').origin;
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin))throw Error('loopback only');
const out=process.env.WORKSHOP_SCREEN_DIR;
if(out)await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:process.env.PW_CHANNEL || 'msedge',headless:true});
try{
  const ctx=await browser.newContext({viewport:{width:1280,height:900},locale:'ko-KR'});
  const admin=await ctx.newPage();admin.setDefaultTimeout(60000);
  await ctx.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  const login=await ctx.request.post(origin+'/api/admin/entry/password/',{data:{password:'mock-recommendations-only'}});
  assert.equal(login.status(),200);
  const {adminToken}=await login.json();
  await ctx.addInitScript(token=>sessionStorage.setItem('flower_admin_token',token),adminToken);
  await admin.goto(origin+'/admin/editions/',{waitUntil:'domcontentloaded',timeout:120000});
  const title='영냥이의 달빛 소원 카드';
  await admin.getByLabel('캐릭터').selectOption('cat');
  await admin.getByLabel('상품명').fill(title);
  await admin.getByRole('button',{name:'초안 저장하기'}).click();
  const edition=admin.getByRole('heading',{name:title,exact:true}).first().locator('..');
  await edition.getByRole('button',{name:'3개 한도 확정하기'}).click();
  await edition.getByRole('button',{name:'1번 발행하기'}).click();
  await edition.getByRole('button',{name:'1번 QR 준비하기'}).click();
  const src=await admin.getByAltText('발행 기록 확인 QR').getAttribute('src');
  const png=PNG.sync.read(Buffer.from(src.split(',')[1],'base64'));
  const url=jsQR(new Uint8ClampedArray(png.data),png.width,png.height).data;
  assert.equal(new URL(url).origin,origin);
  if(out)await admin.screenshot({path:path.join(out,'admin.png'),fullPage:true});
  const guest=await browser.newContext({viewport:{width:390,height:844},locale:'ko-KR'});
  assert.equal((await guest.request.get(origin+'/api/admin/editions/')).status(),401);
  await guest.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  const customer=await guest.newPage();await customer.goto(url,{waitUntil:'domcontentloaded',timeout:120000});
  await customer.getByText('공식 발행기록과 일치합니다.').waitFor({timeout:60000});
  await customer.getByText('3개 한정 · 001번').waitFor();
  await customer.getByText('발행 근거 보기').click();
  assert.ok(await customer.getByText('31337').isVisible());
  assert.ok(await customer.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  const consent=customer.getByRole('button',{name:'필수만 사용'});
  if(await consent.isVisible())await consent.click();
  if(out)await customer.screenshot({path:path.join(out,'customer.png'),fullPage:true});
  await customer.getByLabel('인쇄된 확인 코드').fill('unknown');
  await customer.getByRole('button',{name:'번호 확인하기'}).click();
  await customer.getByText('등록된 발행 기록을 찾을 수 없어요.').waitFor();
  console.log('PASS: admin login → seal → NFT mint → decoded PNG → anonymous mobile proof; 401, unknown code, viewport');
}finally{await browser.close();}
