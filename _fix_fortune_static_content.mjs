function buildStaticSection(type, id, period, data) {
  const meta = PERIOD_META[period];
  const isAnimal = type === 'animal';
  const name = data.kr;
  const emoji = data.emoji;
  const periodKr = meta.kr;

  const faqItems = (data.faq || []).map(([q, a]) =>
    `<details class="fe-faq-item"><summary>${q}</summary><div class="fe-faq-answer">${a}</div></details>`
  ).join('\n  ');

  const compatibleLabel = isAnimal ? '잘 맞는 띠' : '잘 맞는 별자리';
  const compatible = data.compatible || '';
  const dateInfo = isAnimal
    ? `<p><strong>해당 출생년도:</strong> ${data.years}</p>`
    : `<p><strong>출생일:</strong> ${data.dates}</p>`;
  const elementInfo = isAnimal
    ? `<p><strong>오행:</strong> ${data.element} · <strong>계절:</strong> ${data.season}</p>`
    : `<p><strong>원소:</strong> ${data.element} · <strong>지배 행성:</strong> ${data.planet}</p>`;

  return `<section class="fe-static-content" style="margin:0 0 18px;padding:16px;background:rgba(255,255,255,.04);border:1px solid rgba(167,139,250,.18);border-radius:14px;">
  <h2 style="font-size:1.15rem;font-weight:800;color:#e9d5ff;margin-bottom:10px;">${emoji} ${periodKr} ${name} 운세 — 특성 & 심층 가이드</h2>
  <p style="color:rgba(203,195,227,.75);font-size:.82rem;line-height:1.7;margin-bottom:10px;">${meta.desc} 아래에서 ${name}의 기본 기질과 오늘의 행운 정보를 확인하세요.</p>
  ${dateInfo}
  ${elementInfo}
  <p><strong>핵심 기질:</strong> ${data.traits}</p>
  <p><strong>강점:</strong> ${data.strength}</p>
  <p><strong>약점과 보완점:</strong> ${data.weakness}</p>
  <p><strong>${compatibleLabel}:</strong> ${compatible}</p>
  ${isAnimal ? `<p><strong>직업 적성:</strong> ${data.career}</p><p><strong>연애 스타일:</strong> ${data.love}</p><p><strong>재물 성향:</strong> ${data.money}</p><p><strong>건강 포인트:</strong> ${data.health}</p>` : ''}
  <p style="margin-top:10px;font-size:.82rem;color:rgba(203,195,227,.6);">${data.overall}</p>
  <div style="margin-top:12px;border-top:1px solid rgba(167,139,250,.12);padding-top:12px;">
    <strong style="color:#a78bfa;font-size:.8rem;">자주 묻는 질문 (FAQ)</strong>
    <div style="margin-top:8px;">
  ${faqItems}
    </div>
  </div>
</section>`;
}

function processFile(filePath, type, id, period, data) {
  let html = readFileSync(filePath, 'utf8');
  // 이미 패치됐으면 스킵
  if (html.includes('fe-static-content')) return false;
  const staticSection = buildStaticSection(type, id, period, data);
  // <main class="fe-wrap"> 다음에 삽입
  html = html.replace(
    '<div id="fortuneApp">',
    staticSection + '\n  <div id="fortuneApp">'
  );
  writeFileSync(filePath, html, 'utf8');
  return true;
}

