"""Measure the paw baseline in each authored pose; render offsets without moving the stage."""
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
atlas = root / "public/assets/profile-pets/moon-garden-v1"
def paws(tile):
    width, height = tile.size
    mask = bytearray(tile.convert("RGBA").getchannel("A").point(lambda a: 255 if a >= 130 else 0).tobytes())
    largest = []
    for i, value in enumerate(mask):
        if not value:
            continue
        component = [i]
        mask[i] = 0
        for j in component:
            x, y = j % width, j // width
            for k in ([j-1] if x else []) + ([j+1] if x+1 < width else []) + ([j-width] if y else []) + ([j+width] if y+1 < height else []):
                if mask[k]:
                    mask[k] = 0
                    component.append(k)
        if len(component) > len(largest):
            largest = component
    ys = sorted(j // width for j in largest)
    baseline = ys[int(.995 * len(ys))]
    xs = sorted(j % width for j in largest if baseline - height*.075 < j//width <= baseline)
    return (xs[len(xs)//10] + xs[int(.9*len(xs))])/2, baseline

poses = {}
for body in sorted(atlas.glob("*-body.webp")):
    species = body.name.removesuffix("-body.webp")
    offsets = []
    for path, rows in [(body, 3), (atlas / (species+"-sleep.webp"), 1)]:
        with Image.open(path) as img:
            width, height = img.width//4, img.height//rows
            for row in range(rows):
                for col in range(4):
                    x,y=paws(img.crop((col*width,row*height,(col+1)*width,(row+1)*height)))
                    if not offsets:
                        anchor=(x/width,y/height)
                    offsets.append([round((anchor[0]-x/width)*100,2),round((anchor[1]-y/height)*100,2)])
    poses[species]=offsets
out=root/"js/core/profile-pet-anchors.mjs"
out.write_text("// Generated by scripts/build-profile-pet-anchors.py; units are tile percentages.\nexport const pawOffsets = "+json.dumps(poses,separators=(",",":"))+";\n",encoding="utf8")
