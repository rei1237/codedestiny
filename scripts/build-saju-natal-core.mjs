import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
// 정적 셸은 import를 못 하므로 원국 판정 정본(lib/saju/natal-core)을 전역 SajuNatalCore로 묶는다.
const outfile='js/core/saju/natal-core.generated.js';
const result=buildSync({entryPoints:['lib/saju/natal-core/index.mjs'],bundle:true,format:'iife',globalName:'SajuNatalCore',platform:'browser',target:'es2020',charset:'utf8',write:false});
const source='// Generated by scripts/build-saju-natal-core.mjs. Edit lib/saju/natal-core/*.mjs.\n'+result.outputFiles[0].text;
const current=existsSync(outfile)?readFileSync(outfile,'utf8').replace(/\r\n/g,'\n'):null;
if(process.argv.includes('--check')){
  if(current!==source)throw new Error('Saju natal core bundle drift: run node scripts/build-saju-natal-core.mjs');
  console.log('PASS natal-core bundle matches lib/saju/natal-core');
}else if(current!==source)writeFileSync(outfile,source);
