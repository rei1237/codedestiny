import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const outfile='js/core/saju/reading-depth.generated.js';
const result=buildSync({entryPoints:['lib/saju/reading-depth.mjs'],bundle:true,format:'iife',globalName:'SajuReadingDepth',platform:'browser',target:'es2020',charset:'utf8',write:false});
const source='// Generated by scripts/build-saju-reading-depth.mjs. Edit lib/saju/reading-depth.mjs.\n'+result.outputFiles[0].text;
if(!existsSync(outfile)||readFileSync(outfile,'utf8').replace(/\r\n/g,'\n')!==source)writeFileSync(outfile,source);
