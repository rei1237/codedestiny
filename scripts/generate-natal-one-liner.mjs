// 무료 한 줄 성향(60갑자) 생성기.
// lib/saju/reading-depth.mjs 의 일주 문장 중 "첫 문장"만 뽑아 공개 표로 싣는다. 둘째 문장·장별 해석은 서버 전용이다.
// 일주 표기(甲子 등)만 쓰고 용신·격국 단정은 넣지 않는다.
import { writeFileSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = resolve(root, "js/core/saju/natal-one-liner.generated.js");

export function firstSentence(text) {
  const clean = String(text || "").trim();
  const match = clean.match(/^[^.!?]+[.!?]/);
  return (match ? match[0] : clean).trim();
}

export async function buildOneLinerTable() {
  const depth = await import(pathToFileURL(resolve(root, "lib/saju/reading-depth.mjs")).href);
  const table = {};
  for (const key of depth.DAY_KEYS) table[key] = firstSentence(depth.PILLAR_NOTES[key]);
  return table;
}

export function renderSource(table) {
  return [
    "// Generated by scripts/generate-natal-one-liner.mjs. 일주 문장 원천(lib/saju/reading-depth.mjs)의 첫 문장만 싣는다. 직접 고치지 않는다.",
    "(function (root) {",
    "  'use strict';",
    "  var TABLE = " + JSON.stringify(table, null, 2).replace(/\n/g, "\n  ") + ";",
    "  root.CdSajuNatalOneLiner = {",
    "    get: function (dayPillarKey) {",
    "      var key = String(dayPillarKey || '').trim();",
    "      return Object.prototype.hasOwnProperty.call(TABLE, key) ? TABLE[key] : '';",
    "    }",
    "  };",
    "})(typeof window !== 'undefined' ? window : globalThis);",
    "",
  ].join("\n");
}

export async function writeNatalOneLiner() {
  const table = await buildOneLinerTable();
  const next = renderSource(table);
  let prev = "";
  try { prev = readFileSync(outfile, "utf8"); } catch { /* first run */ }
  if (prev !== next) writeFileSync(outfile, next, "utf8");
  return { count: Object.keys(table).length, changed: prev !== next };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const { count, changed } = await writeNatalOneLiner();
  console.log(`natal-one-liner: ${count}개 일주${changed ? " 기록" : " (변경 없음)"}`);
}
