import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
// Generated browser adapter from the same explicit policy the Worker imports.
export function writeFreeFortuneBrowser(root = process.cwd()) {
  // Normalize to LF: on Windows (core.autocrlf=true) the source is checked out with CRLF,
  // which made the generated copies mixed-EOL and checkout-dependent.
  const source = readFileSync(resolve(root, 'lib/payment/free-fortune-policy.mjs'), 'utf8').replace(/\r\n/g, '\n');
  if (/^import /m.test(source)) throw new Error('Free policy adapter requires a standalone policy module');
  const browser = '// GENERATED by scripts/generate-free-fortune-browser.mjs. Do not edit.\n(function(root){\n' + source.replace(/^export /gm, '') + '\nroot.cdIsFreeFortuneFeatureKey = isFreeFortuneFeatureKey;\nroot.cdFreeFortuneFeatureKeys = FREE_FORTUNE_FEATURE_KEYS;\n})(window);\n';
  writeFileSync(resolve(root, 'js/core/free-fortune-policy.js'), browser);
  writeFileSync(resolve(root, 'js/core/free-fortune-policy.mjs'), '// GENERATED by scripts/generate-free-fortune-browser.mjs. Do not edit.\n' + source);
}
writeFreeFortuneBrowser();
