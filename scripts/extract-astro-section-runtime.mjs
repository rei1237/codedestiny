import fs from 'node:fs';
import ts from 'typescript';
// Bundles the paid Western-astrology counsel bodies (worker/lib/astro-section/*.src.js) with the helpers they call,
// copied verbatim from js/saju-engine.js: the astro counsel IIFE (the statement that declares ASTRO_COUNSEL_MARKER)
// and the top-level text helpers. No formula is edited here: --check fails when js/saju-engine.js, the paid sources
// or the public sajuEngine translations drift. A second bundle (synastry-runtime.generated.mjs) carries the per-use
// synastry body with the celebrity data block.
const OUT = 'worker/lib/astro-section/runtime.generated.mjs';
const SOURCES = ['worker/lib/astro-section/paid-counsel.src.js', 'worker/lib/astro-section/paid-stellar.src.js'];
const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const parse = (file, text) => ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
function ownNames(n) {
  if (ts.isFunctionDeclaration(n) && n.name) return [n.name.text];
  if (ts.isVariableStatement(n)) return n.declarationList.declarations.filter(d => ts.isIdentifier(d.name)).map(d => d.name.text);
  return [];
}
function refs(node) {
  const out = new Set();
  (function visit(n) {
    if (ts.isIdentifier(n) && !(ts.isPropertyAccessExpression(n.parent) && n.parent.name === n) && !(ts.isPropertyAssignment(n.parent) && n.parent.name === n)) out.add(n.text);
    ts.forEachChild(n, visit);
  })(node);
  return out;
}
// Returns the statements (source order) that `startRefs` need from `statements`.
function closure(statements, startRefs, stop) {
  const byName = new Map();
  for (const n of statements) for (const k of ownNames(n)) byName.set(k, n);
  const picked = new Set(); const queue = [...startRefs];
  while (queue.length) {
    const k = queue.pop(); const n = byName.get(k);
    if (!n || stop.has(k) || picked.has(n)) continue;
    picked.add(n); for (const r of refs(n)) queue.push(r);
  }
  return statements.filter(n => picked.has(n));
}

const paid = SOURCES.map((file) => { const text = read(file); return { file, text, ast: parse(file, text) }; });
const paidNames = new Set(paid.flatMap(({ ast }) => ast.statements.flatMap(ownNames)));
const paidRefs = paid.flatMap(({ ast }) => [...refs(ast)]);

const engineAst = parse('saju-engine.js', read('js/saju-engine.js'));
const counselIife = engineAst.statements.find(n => ts.isExpressionStatement(n) && n.getText(engineAst).includes("var ASTRO_COUNSEL_MARKER = '"));
if (!counselIife) throw new Error('Astro counsel IIFE not found in js/saju-engine.js');
let counselFn; (function find(n) { if (counselFn) return; if (ts.isFunctionExpression(n)) { counselFn = n; return; } ts.forEachChild(n, find); })(counselIife);
const counselNodes = closure(counselFn.body.statements, paidRefs, paidNames);
const counselNames = new Set(counselNodes.flatMap(ownNames));
for (const name of paidNames) if (!/^_astroCounsel/.test(name)) throw new Error(`Paid source declares a non-counsel name: ${name}`);
const shellNodes = closure(engineAst.statements, [...paidRefs, ...counselNodes.flatMap(n => [...refs(n)])], new Set([...paidNames, ...counselNames]));
const counsel = counselNodes.map(n => n.getText(engineAst));
const shell = shellNodes.map(n => n.getText(engineAst));

// Only the sajuEngine keys these bodies read go into the server copy; Korean comes from the shell table itself.
const I18N_KEYS = [...new Set([...paid.map(p => p.text), ...counsel, ...shell].join('\n').match(/_sajuEngineText\("([^"]+)"\)/g).map(m => m.slice(17, -2)))].sort();
const i18n = {};
for (const file of fs.readdirSync('public/i18n').filter(f => f.endsWith('.json')).sort()) {
  const table = JSON.parse(fs.readFileSync(`public/i18n/${file}`, 'utf8')).sajuEngine || {};
  i18n[file.slice(0, -5)] = Object.fromEntries(I18N_KEYS.map(k => [k, table[k] || '']));
}

// Bodies are pasted unindented: re-indenting would change multi-line string literals.
const text = `// Generated by scripts/extract-astro-section-runtime.mjs — do not edit. Paid bodies live in
// worker/lib/astro-section/*.src.js; helpers are copied verbatim from the js/saju-engine.js astro counsel IIFE
// and its top-level text helpers.

const I18N = ${JSON.stringify(i18n)};

// Every call builds fresh helper state, so no request sees another request's chart or language.
export function createAstroSectionRuntime(ctx) {
  const lang = String((ctx && ctx.lang) || 'ko');
  const window = {
    location: { search: '', pathname: '/', hostname: '' },
    localStorage: { getItem: function () { return null; } },
    cdGetCurrentLanguage: function () { return lang; },
    cdTranslate: function (key) {
      var table = I18N[_sajuEngineNormalizeLang(lang).toLowerCase()] || {};
      return table[String(key).replace(/^sajuEngine\\./, '')] || 'Translation pending';
    }
  };
  const document = { cookie: '' };

  // ── js/saju-engine.js top-level text helpers ──
${shell.join('\n')}

  // ── js/saju-engine.js astro counsel helpers ──
${counsel.join('\n')}

${paid.map(({ file, text: body }) => `  // ── ${file} ──\n${body.trim()}`).join('\n\n')}

  return { ${[...paidNames].filter(n => /Bodies$/.test(n)).map(n => `${n}: ${n}`).join(', ')} };
}
`;
// ── 시나스트리 궁합(compat-astro-synastry · compat-astro-direct-synastry) — 회당 결제 본문 ──
// worker/lib/astro-section/paid-synastry.src.js 를 원본의 유명인 자료 블록(CELEB_CATS 부터 populateCelebList 직전까지,
// 국적·좌표 보정과 정규화 IIFE 포함)과 그것들이 부르는 최상위 텍스트 헬퍼와 함께 묶는다.
const SYN_OUT = 'worker/lib/astro-section/synastry-runtime.generated.mjs';
const SYN_SOURCE = 'worker/lib/astro-section/paid-synastry.src.js';
const synText = read(SYN_SOURCE);
const synAst = parse(SYN_SOURCE, synText);
const synNames = new Set(synAst.statements.flatMap(ownNames));
for (const name of synNames) if (!/^(_sy[A-Z]|_astroSynastry|_astroHouseLabel$|_astroPromptEscapeHtml$|_astroBuildIncludedSynastryPrompt)/.test(name)) throw new Error(`Synastry source declares an unexpected name: ${name}`);
const celebStart = engineAst.statements.findIndex(n => ownNames(n).includes('CELEB_CATS'));
const celebEnd = engineAst.statements.findIndex(n => ownNames(n).includes('populateCelebList'));
if (celebStart < 0 || celebEnd <= celebStart) throw new Error('Celebrity data block not found in js/saju-engine.js');
const celebNodes = engineAst.statements.slice(celebStart, celebEnd);
const celebNames = new Set(celebNodes.flatMap(ownNames));
for (const name of ['CELEBS', 'COUNTRY_CONFIG', 'GLOBAL_CELEBS', 'resolveCelebProfile']) if (!celebNames.has(name)) throw new Error(`Celebrity data block lost ${name}`);
const synShellNodes = closure(engineAst.statements, [...refs(synAst), ...celebNodes.flatMap(n => [...refs(n)])], new Set([...synNames, ...celebNames]));
const synShell = synShellNodes.map(n => n.getText(engineAst));
const celeb = celebNodes.map(n => n.getText(engineAst));
const SYN_I18N_KEYS = [...new Set([synText, ...celeb, ...synShell].join('\n').match(/_sajuEngineText\("([^"]+)"\)/g).map(m => m.slice(17, -2)))].sort();
const synI18n = {};
for (const file of fs.readdirSync('public/i18n').filter(f => f.endsWith('.json')).sort()) {
  const table = JSON.parse(fs.readFileSync(`public/i18n/${file}`, 'utf8')).sajuEngine || {};
  synI18n[file.slice(0, -5)] = Object.fromEntries(SYN_I18N_KEYS.map(k => [k, table[k] || '']));
}
const synOut = `// Generated by scripts/extract-astro-section-runtime.mjs — do not edit. The paid synastry body lives in
// ${SYN_SOURCE}; the celebrity data block and text helpers are copied verbatim from js/saju-engine.js.

const I18N = ${JSON.stringify(synI18n)};

// Every call builds fresh helper state (celebrity list included), so no request sees another request's data or language.
export function createAstroSynastryRuntime(ctx) {
  const lang = String((ctx && ctx.lang) || 'ko');
  const window = {
    location: { search: '', pathname: '/', hostname: '' },
    localStorage: { getItem: function () { return null; } },
    cdGetCurrentLanguage: function () { return lang; },
    cdTranslate: function (key) {
      var table = I18N[_sajuEngineNormalizeLang(lang).toLowerCase()] || {};
      return table[String(key).replace(/^sajuEngine\\./, '')] || 'Translation pending';
    }
  };
  const document = { cookie: '' };

  // ── js/saju-engine.js top-level text helpers ──
${synShell.join('\n')}

  // ── js/saju-engine.js celebrity data block ──
${celeb.join('\n')}

  // ── ${SYN_SOURCE} ──
${synText.trim()}

  return { ${[...synNames].filter(n => /^_astroSynastry/.test(n)).map(n => `${n}: ${n}`).join(', ')} };
}
`;

for (const [file, body, label] of [[OUT, text, `${shell.length} shell + ${counsel.length} counsel statements, ${paidNames.size} paid declarations`], [SYN_OUT, synOut, `${synShell.length} shell + ${celeb.length} celebrity statements, ${synNames.size} synastry declarations`]]) {
  if (process.argv.includes('--write')) {
    fs.writeFileSync(file, body);
    console.log(`Wrote ${file}: ${label}.`);
  } else {
    if (read(file) !== body) throw new Error(`Astro section runtime drift (${file}): run node scripts/extract-astro-section-runtime.mjs --write`);
    console.log(`PASS ${file} matches its sources (${label}).`);
  }
}
