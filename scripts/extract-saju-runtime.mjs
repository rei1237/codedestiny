import fs from 'node:fs';
import ts from 'typescript';
import { createHash } from 'node:crypto';
const sourcePath = new URL('../js/saju-engine.js', import.meta.url);
const source = fs.readFileSync(sourcePath, 'utf8');
const ast = ts.createSourceFile('saju-engine.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const declarations = new Map();
for (const node of ast.statements) {
  if (ts.isFunctionDeclaration(node) && node.name) declarations.set(node.name.text, node.getText(ast));
  if (ts.isVariableStatement(node)) for (const d of node.declarationList.declarations)
    if (ts.isIdentifier(d.name)) declarations.set(d.name.text, `var ${d.getText(ast)};`);
}
const roots = ['_applyTrueSolarTimeCorrection', '_cdCivilDayPillar', '_cdHourPillarFromDayStem', 'calcPower', 'calcNatalElement', 'analyzeJohu', 'detectJong', 'applyRuntimeYongshinPolicy', 'resolveBirthTimezoneOffset'];
// The shared diary engine already exports these exact shell formulas and tables.
// Its parity test executes both implementations; do not introduce a third copy.
const reusable = new Set(['GAN','JI','SHENG','KE','whoControls','parentOf','CD_JANGGAN','calcPower','detectJong']);
const reused = new Set();
const selected = new Map();
function include(name) {
  if(reusable.has(name)){reused.add(name);return;}
  if (selected.has(name) || !declarations.has(name)) return;
  const code = declarations.get(name); selected.set(name, code);
  const fragment = ts.createSourceFile('fragment.js', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  function visit(n) { if (ts.isIdentifier(n) && !(ts.isPropertyAccessExpression(n.parent) && n.parent.name === n)) include(n.text); ts.forEachChild(n, visit); }
  visit(fragment);
}
roots.forEach(include);
for (const name of roots) if (!selected.has(name) && !reused.has(name)) throw new Error(`Missing calculation root: ${name}`);
const text = `// Generated by scripts/extract-saju-runtime.mjs; original formulas unchanged.\nimport { ${[...reused].join(', ')} } from '../../../lib/saju/natal-power.js';\n${[...selected.values()].join('\n\n')}\nexport { ${roots.join(', ')} };\n`;
if (!process.argv.includes('--write')) {
  const actual = fs.readFileSync('worker/yeongnyangi/fortune/saju-runtime.mjs', 'utf8');
  if (actual.replace(/\r\n/g, '\n') !== text.replace(/\r\n/g, '\n')) throw new Error('Saju runtime drift: run node scripts/extract-saju-runtime.mjs --write');
  console.log(`PASS ${selected.size} calculation declarations match js/saju-engine.js`);
} else {
  fs.writeFileSync('worker/yeongnyangi/fortune/saju-runtime.mjs', text);
  fs.writeFileSync('worker/yeongnyangi/fortune/saju-runtime-provenance.json', JSON.stringify({sourcePath:'js/saju-engine.js', sha256:createHash('sha256').update(source).digest('hex'), symbols:[...selected].map(([name,code])=>({name,sha256:createHash('sha256').update(code).digest('hex')}))},null,2));
  console.log(`Extracted ${selected.size} declarations without formula edits.`);
}
