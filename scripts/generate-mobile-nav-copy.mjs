// A tiny SSR subset of the existing browser dictionaries; no full dictionary enters the client bundle.
import { readFileSync, writeFileSync } from "node:fs";
const source = readFileSync("app/_lib/mobile-tabs.ts", "utf8");
const keys = [...new Set([
  ...[...source.matchAll(/(?:transKey|ariaTransKey):\s*"([^"]+)"/g)].map(m => m[1]),
  source.match(/MNAV_TOGGLE_TRANS_KEY\s*=\s*"([^"]+)"/)[1],
])];
function valueAtPath(dictionary, key) {
  if (typeof dictionary[key] === "string") return dictionary[key];
  return key.split(".").reduce((value, segment) => value?.[segment], dictionary);
}
const data = {};
for (const [locale, filename] of Object.entries({ ja: "ja", en: "en", zh: "zh-cn", "zh-TW": "zh-tw" })) {
  const dictionary = JSON.parse(readFileSync(`public/i18n/${filename}.json`, "utf8"));
  data[locale] = Object.fromEntries(keys.map(key => {
    const value = valueAtPath(dictionary, key);
    if (typeof value !== "string" || !value || /[가-힣]/.test(value)) throw new Error(`Missing native mobile nav: ${locale}/${key}`);
    return [key, value];
  }));
}
const output = `// Generated by node scripts/generate-mobile-nav-copy.mjs; source: public/i18n.\nexport const MOBILE_NAV_SSR_COPY: Record<string, Record<string, string>> = ${JSON.stringify(data, null, 2)};\n`;
const destination = "lib/i18n/mobile-nav-ssr-copy.ts";
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) throw new Error("Mobile nav SSR copy drift; run node scripts/generate-mobile-nav-copy.mjs");
} else writeFileSync(destination, output);
console.log(`[mobile-nav-copy] ${keys.length} keys × ${Object.keys(data).length} locales OK`);
