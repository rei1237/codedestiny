// Vendor official, immutable WOFF2 subsets. No cloud writes or deployment.
import {mkdir, readFile, writeFile, unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'public/assets/fonts/ui');
const output = path.join(root, 'styles/fonts-ui.generated.css');
const manifestPath = path.join(directory, 'manifest.json');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
if (process.argv.includes('--check')) {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  if (hash(await readFile(output)) !== manifest.cssSha256) throw new Error('UI font CSS differs from manifest');
  for (const asset of manifest.assets) {
    if (hash(await readFile(path.join(directory, asset.file))) !== asset.sha256) throw new Error('Invalid font asset: ' + asset.file);
  }
  console.log(`UI fonts: ${manifest.assets.length} assets verified; same-origin WOFF2 subsets, licenses included`);
  process.exit(0);
}
const sources = [
  {family:'CodeDestinyRounded', name:'Jua', css:'https://fonts.googleapis.com/css2?family=Jua&display=swap', license:'https://raw.githubusercontent.com/google/fonts/main/ofl/jua/OFL.txt'},
  {family:'CodeDestinyBody', name:'Pretendard', css:'https://raw.githubusercontent.com/orioncactus/pretendard/v1.3.9/packages/pretendard/dist/web/variable/pretendardvariable-dynamic-subset.css', license:'https://raw.githubusercontent.com/orioncactus/pretendard/v1.3.9/LICENSE'},
];
async function fetchBytes(url) {
  const response = await fetch(url, {headers:{'User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36'}});
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return Buffer.from(await response.arrayBuffer());
}
await mkdir(directory, {recursive:true});
const previous = await readFile(manifestPath, 'utf8').then(JSON.parse).catch(() => ({assets:[]}));
const assets = [], css = ['/* Generated by scripts/build-ui-font-assets.mjs. Official OFL subsets; same-origin only. */'];
for (const source of sources) {
  const upstreamCss = (await fetchBytes(source.css)).toString('utf8');
  const blocks = [...upstreamCss.matchAll(/@font-face\s*\{[^}]+\}/g)].map(match => match[0]);
  if (!blocks.length) throw new Error('Missing font faces: ' + source.name);
  const license = await fetchBytes(source.license);
  const licenseFile = `${source.name}-OFL.txt`;
  await writeFile(path.join(directory, licenseFile), license);
  assets.push({file:licenseFile, url:source.license, sha256:hash(license)});
  const rendered = await Promise.all(blocks.map(async block => {
    const src = block.match(/url\(['"]?([^'"\s)]+)['"]?\)/)?.[1];
    if (!src) throw new Error('Missing font URL');
    const url = new URL(src, source.css).href;
    const bytes = await fetchBytes(url);
    if (bytes.subarray(0,4).toString() !== 'wOF2') throw new Error('Expected WOFF2: ' + url);
    const file = `${source.name}-${hash(bytes).slice(0,16)}.woff2`;
    await writeFile(path.join(directory, file), bytes);
    assets.push({file, url, sha256:hash(bytes), bytes:bytes.length});
    return block.replace(/font-family:\s*[^;]+;/, `font-family: '${source.family}';`)
      .replace(/src:\s*[^;]+;/, `src: url('/assets/fonts/ui/${file}') format('woff2');`)
      .replace(/font-display:\s*[^;]+;/, 'font-display: swap;');
  }));
  css.push(...rendered);
}
const result = css.join('\n') + '\n';
await writeFile(output, result);
await writeFile(manifestPath, JSON.stringify({sources, cssSha256:hash(result), assets:assets.sort((a,b)=>a.file.localeCompare(b.file))}, null, 2) + '\n');
for (const asset of previous.assets) {
  if (path.basename(asset.file) !== asset.file) throw new Error('Invalid old asset path');
  if (!assets.some(current => current.file === asset.file)) await unlink(path.join(directory, asset.file));
}
console.log(`Vendored ${assets.length} UI font assets (${assets.reduce((sum,a)=>sum+(a.bytes||0),0)} bytes); loaded by unicode-range as needed`);
