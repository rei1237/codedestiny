import { DIFFERENTIATION_FAQS } from "../../lib/brand/differentiation-faqs.mjs";

function differentiationFaq(question) {
  const item = DIFFERENTIATION_FAQS.find(faq => faq.question === question);
  if (!item) throw new Error(`Missing differentiation FAQ: ${question}`);
  return item;
}

