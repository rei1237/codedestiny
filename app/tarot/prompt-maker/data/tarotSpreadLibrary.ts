export function normalizePromptMakerLocale(locale: string | null | undefined): PromptMakerLocale {
  const value = String(locale || "ko");
  if (value === "zh" || value === "zh-CN") return "zh-CN";
  if (value === "zh-TW") return "zh-TW";
  if (["ko", "en", "ja", "vi", "hi", "es", "fr", "de", "nl", "ms"].includes(value)) return value as PromptMakerLocale;
  return "en";
}

export function getLocalizedPromptMakerData(locale: string | null | undefined): LocalizedPromptMakerData {
  const normalized = normalizePromptMakerLocale(locale);
  if (normalized === "ko") {
    return {
      categoryLabel: CATEGORY_LABEL,
      questionChips: QUESTION_CHIPS,
      defaultQuestionByCategory: DEFAULT_QUESTION_BY_CATEGORY,
    };
  }
  return {
    categoryLabel: CATEGORY_LABEL_LOCALIZED[normalized] || CATEGORY_LABEL_LOCALIZED.en,
    questionChips: QUESTION_CHIPS_LOCALIZED[normalized] || QUESTION_CHIPS_LOCALIZED.en,
    defaultQuestionByCategory: DEFAULT_QUESTION_BY_CATEGORY_LOCALIZED[normalized] || DEFAULT_QUESTION_BY_CATEGORY_LOCALIZED.en,
  };
}

