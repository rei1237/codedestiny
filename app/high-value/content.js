export const HIGH_VALUE_PAGES = RAW_HIGH_VALUE_PAGES.map((page) => ({
  ...page,
  sections: [...page.sections, ...buildExtendedSections(page)],
}));

export function getHighValuePageBySlug(slug) {
  return HIGH_VALUE_PAGES.find((item) => item.slug === slug) || null;
}

function normalizeCategorySlug(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export const HIGH_VALUE_CATEGORIES = Array.from(
  new Map(
    HIGH_VALUE_PAGES.map((item) => {
      const slug = normalizeCategorySlug(item.category);
      return [slug, { slug, name: item.category }];
    }),
  ).values(),
);

export function getHighValuePagesByCategory(categorySlug) {
  return HIGH_VALUE_PAGES.filter(
    (item) => normalizeCategorySlug(item.category) === String(categorySlug || "").toLowerCase(),
  );
}

export function getHighValueCategoryBySlug(categorySlug) {
  return HIGH_VALUE_CATEGORIES.find((item) => item.slug === String(categorySlug || "").toLowerCase()) || null;
}
