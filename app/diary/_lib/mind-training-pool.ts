export interface DiaryTrainingPick {
  text: string;
  index: number;
}

/**
 * 풀에서 하나를 고른다. 직전과 같은 자리가 나오면 한 칸 이상 옮긴다 —
 * 셸 `:2325-2328` 과 같은 식이다(연달아 같은 문장이 나오면 뽑기 자체가 의미를 잃는다).
 */
function pickFrom(pool: readonly string[], lastIndex: number): DiaryTrainingPick {
  let index = Math.floor(Math.random() * pool.length);
  if (pool.length > 1 && index === lastIndex) {
    index = (index + 1 + Math.floor(Math.random() * (pool.length - 1))) % pool.length;
  }
  return { text: pool[index], index };
}

export function pickTrainingScene(
  keyword: DiaryTrainingKeyword,
  lastIndex: number,
): DiaryTrainingPick {
  return pickFrom(SCENES[keyword], lastIndex);
}

export function pickTrainingAffirmation(
  keyword: DiaryTrainingKeyword,
  lastIndex: number,
): DiaryTrainingPick {
  return pickFrom(AFFIRMATIONS[keyword], lastIndex);
}
