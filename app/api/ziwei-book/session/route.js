const ZHI_LIST = ["子","丑","寅","卯","辰","巳","午","未","申","酉","戌","亥"];
const ZHI_KR   = ["자","축","인","묘","진","사","오","미","신","유","술","해"];
const GAN_LIST = ["甲","乙","丙","丁","戊","己","庚","辛","壬","癸"];
const GAN_KR   = ["갑","을","병","정","무","기","경","신","임","계"];

// 명궁 기준 12궁 이름 (offset 0=명궁, 1=형제궁, ...)
const PALACE_FROM_MING = [
  "명궁","형제궁","부모궁","재백궁","자녀궁","노복궁",
  "부처궁","질액궁","천이궁","관록궁","전택궁","복덕궁"
];

// 사화 표
const SIHUA_TABLE = {
  甲: { rec:"염정", pow:"파군", sci:"무곡", bad:"태양" },
  乙: { rec:"천기", pow:"천량", sci:"자미", bad:"태음" },
  丙: { rec:"천동", pow:"천기", sci:"문창", bad:"염정" },
  丁: { rec:"태음", pow:"천동", sci:"천기", bad:"거문" },
  戊: { rec:"탐랑", pow:"태음", sci:"우필", bad:"천기" },
  己: { rec:"무곡", pow:"탐랑", sci:"천량", bad:"문곡" },
  庚: { rec:"태양", pow:"무곡", sci:"태음", bad:"천동" },
  辛: { rec:"거문", pow:"태양", sci:"문곡", bad:"문창" },
  壬: { rec:"천량", pow:"자미", sci:"좌보", bad:"무곡" },
  癸: { rec:"파군", pow:"거문", sci:"태음", bad:"탐랑" },
};

// 명국 시작 나이 (수2국=2, 목3국=3, 금4국=4, 토5국=5, 화6국=6)
const JU_NAMES = { 2:"水2局", 3:"木3局", 4:"金4局", 5:"土5局", 6:"火6局" };

function calcZiweiServer(year, month, day, hour) {
  try {
    const solar = Solar.fromYmdHms(year, month, day, Math.max(0, hour), 0, 0);
    const lunar = solar.getLunar();
    const lmonth  = Math.abs(Number(lunar.getMonth()));
    const lday    = Number(lunar.getDay());
    const yearGan = String(lunar.getYearGan() || "甲");
    const yearZhi = String(lunar.getYearZhi() || "子");
    const lunarYear = Number(lunar.getYear());

    // 시(時) 인덱스 (子시=0, 丑시=1, ..., 亥시=11)
    const hourIdx = (hour === 23 || hour === 0) ? 0 : Math.floor((hour + 1) / 2);

    // 명궁(命宮) 인덱스 — 음력월과 출생시각으로 결정
    const mengBaseIdx = (2 + lmonth - 1) % 12;
    const mengIdx = (mengBaseIdx - hourIdx + 12) % 12;

    // 신궁(身宮) 인덱스
    const shenIdx = (mengBaseIdx + hourIdx) % 12;

    // 명국(命局) 계산 (국수 ju: 2~6)
    const ygIdx = GAN_LIST.indexOf(yearGan);
    const inStart = [2,4,6,8,0][((ygIdx % 5) + 5) % 5];
    const sMap = { 甲:1,乙:1,丙:2,丁:2,戊:3,己:3,庚:4,辛:4,壬:5,癸:5 };
    const bMap = { 0:1,1:1,2:2,3:2,4:3,5:3,6:1,7:1,8:2,9:2,10:3,11:3 };
    const gongGan = {};
    for (let z = 0; z < 12; z++) gongGan[ZHI_LIST[z]] = GAN_LIST[(inStart + ((z - 2 + 12) % 12)) % 10];
    const mgGan = gongGan[ZHI_LIST[mengIdx]] || yearGan;
    const wVal = Math.min(5, Math.max(1, (sMap[mgGan] || 1) + (bMap[mengIdx] || 1)));
    const juMap = { 1:3, 2:4, 3:2, 4:6, 5:5 };
    const ju = juMap[wVal] || 4;

    // 자미성 위치 계산
    let q = Math.floor(lday / ju), r = lday % ju, add = 0;
    if (r !== 0) { add = ju - r; q = Math.floor((lday + add) / ju); }
    let pos = add > 0 ? (add % 2 === 1 ? q - add : q + add) : q;
    while (pos <= 0) pos += 12;
    while (pos > 12) pos -= 12;
    const zPos = (pos + 1) % 12;
    const fPos = (16 - zPos) % 12;

    // 14주성 배치
    const mainStars = Array.from({ length: 12 }, () => []);
    mainStars[zPos].push("자미");
    mainStars[(zPos + 11) % 12].push("천기");
    mainStars[(zPos + 9)  % 12].push("태양");
    mainStars[(zPos + 8)  % 12].push("무곡");
    mainStars[(zPos + 7)  % 12].push("천동");
    mainStars[(zPos + 4)  % 12].push("염정");
    mainStars[fPos].push("천부");
    mainStars[(fPos + 1)  % 12].push("태음");
    mainStars[(fPos + 2)  % 12].push("탐랑");
    mainStars[(fPos + 3)  % 12].push("거문");
    mainStars[(fPos + 4)  % 12].push("천상");
    mainStars[(fPos + 5)  % 12].push("천량");
    mainStars[(fPos + 6)  % 12].push("칠살");
    mainStars[(fPos + 10) % 12].push("파군");

    // 보조성 배치
    const auxStars = Array.from({ length: 12 }, () => []);
    auxStars[(10 - hourIdx + 12) % 12].push("문창");
    auxStars[(4 + hourIdx) % 12].push("문곡");
    auxStars[(4 + lmonth - 1) % 12].push("좌보");
    auxStars[(10 - (lmonth - 1) + 12) % 12].push("우필");
    const luCunMap = { 甲:2,乙:3,丙:5,丁:6,戊:5,己:6,庚:8,辛:9,壬:11,癸:0 };
    const kuiMap   = { 甲:1,乙:0,丙:11,丁:11,戊:1,己:0,庚:1,辛:2,壬:3,癸:3 };
    const yueMap   = { 甲:7,乙:8,丙:9,丁:9,戊:7,己:8,庚:7,辛:6,壬:5,癸:5 };
    const maMap    = { 申:2,子:2,辰:2,亥:5,卯:5,未:5,寅:8,午:8,戌:8,巳:11,酉:11,丑:11 };
    if (yearGan in luCunMap) auxStars[luCunMap[yearGan]].push("녹존");
    if (yearGan in kuiMap)   auxStars[kuiMap[yearGan]].push("천괴");
    if (yearGan in yueMap)   auxStars[yueMap[yearGan]].push("천월");
    if (yearZhi in maMap)    auxStars[maMap[yearZhi]].push("천마");

    // 살성(煞星) 배치
    const badStars = Array.from({ length: 12 }, () => []);
    const yangMap = { 甲:3,乙:4,丙:6,丁:7,戊:6,己:7,庚:9,辛:10,壬:0,癸:1 };
    const tuoMap  = { 甲:1,乙:2,丙:4,丁:5,戊:4,己:5,庚:7,辛:8,壬:10,癸:11 };
    if (yearGan in yangMap) {
      badStars[yangMap[yearGan]].push("경양");
      badStars[tuoMap[yearGan]].push("타라");
    }
    badStars[(11 - hourIdx + 12) % 12].push("지공");
    badStars[(11 + hourIdx)       % 12].push("지겁");

    // 사화(四化) — yearGan 기준
    const sihua = SIHUA_TABLE[yearGan] || {};
    const sihuaLocations = {};
    for (let i = 0; i < 12; i++) {
      for (const star of mainStars[i]) {
        if (star === sihua.rec) sihuaLocations.rec = { star, idx: i };
        if (star === sihua.pow) sihuaLocations.pow = { star, idx: i };
        if (star === sihua.sci) sihuaLocations.sci = { star, idx: i };
        if (star === sihua.bad) sihuaLocations.bad = { star, idx: i };
      }
      // 보조성에도 화과/화기 가능
      for (const star of auxStars[i]) {
        if (star === sihua.sci && !sihuaLocations.sci) sihuaLocations.sci = { star, idx: i };
        if (star === sihua.bad && !sihuaLocations.bad) sihuaLocations.bad = { star, idx: i };
      }
    }

    return {
      mengIdx, shenIdx, mainStars, auxStars, badStars,
      yearGan, yearZhi, lunarYear, lmonth, lday, hourIdx, ju,
      sihuaLocations,
    };
  } catch (_e) {
    return null;
  }
}

function buildZiweiDataString(calc, name, gender, birthY, birthM, birthD, birthH) {
  if (!calc) return null;
  const { mengIdx, shenIdx, mainStars, auxStars, badStars,
          yearGan, yearZhi, lunarYear, lmonth, lday, hourIdx, ju,
          sihuaLocations } = calc;

  const palName = (idx) => PALACE_FROM_MING[(idx - mengIdx + 12) % 12];
  const zhiStr  = (idx) => ZHI_LIST[idx] + "궁";

  const lines = [];
  lines.push("【자미두수 분석 대상】");
  lines.push("이름: " + (name || "사용자"));
  lines.push("성별: " + (gender === "F" ? "여성" : gender === "M" ? "남성" : (gender || "미상")));
  lines.push(`생년월일(양력): ${birthY}년 ${birthM}월 ${birthD}일`);
  if (birthH >= 0) lines.push(`출생 시각: ${birthH}시`);
  lines.push(`음력 생년월일: ${lunarYear}년 ${lmonth}월 ${lday}일`);
  lines.push(`생년 천간(天干): ${yearGan} / 생년 지지(地支): ${yearZhi}`);
  lines.push(`명국(命局): ${JU_NAMES[ju] || ju + "국"}`);
  const currentAge = 2026 - birthY + 1;
  lines.push(`현재 나이: ${currentAge}세 (만 ${currentAge - 1}세) / 기준년: 2026년 丙午年`);

  lines.push("");
  lines.push("【12궁 완전 배치 — 주성·보성·살성】");
  for (let i = 0; i < 12; i++) {
    const pn = palName(i);
    const zhi = ZHI_LIST[i];
    const parts = [];
    if (mainStars[i].length) parts.push("주성: " + mainStars[i].join("·"));
    if (auxStars[i].length)  parts.push("보성: " + auxStars[i].join("·"));
    if (badStars[i].length)  parts.push("살성: " + badStars[i].join("·"));
    if (!parts.length) parts.push("(공궁)");
    lines.push(`${pn}[${zhi}]: ${parts.join(" | ")}`);
  }

  lines.push("");
  lines.push("【명궁(命宮) 상세】");
  lines.push(`명궁 위치: ${ZHI_LIST[mengIdx]}궁 (${ZHI_KR[mengIdx]}궁)`);
  lines.push(`명궁 주성: ${mainStars[mengIdx].join("·") || "(없음)"}`);
  lines.push(`명궁 보성: ${auxStars[mengIdx].join("·") || "(없음)"}`);
  lines.push(`명궁 살성: ${badStars[mengIdx].join("·") || "(없음)"}`);

  lines.push("");
  lines.push("【신궁(身宮) 상세】");
  lines.push(`신궁 위치: ${ZHI_LIST[shenIdx]}궁 (${ZHI_KR[shenIdx]}궁)`);
  lines.push(`신궁 주성: ${mainStars[shenIdx].join("·") || "(없음)"}`);
  lines.push(`신궁 보성: ${auxStars[shenIdx].join("·") || "(없음)"}`);
  lines.push(`신궁과 명궁 관계: ${mengIdx === shenIdx ? "동궁(同宮) — 명·신이 일치, 집중력 극대화" : "이궁(異宮) — 명·신 분리, 이중 에너지 구조"}`);

  lines.push("");
  lines.push("【사화(四化) 배치】");
  if (sihuaLocations.rec) {
    const r = sihuaLocations.rec;
    lines.push(`화록(化祿): ${r.star}성 → ${palName(r.idx)}[${ZHI_LIST[r.idx]}]`);
  }
  if (sihuaLocations.pow) {
    const r = sihuaLocations.pow;
    lines.push(`화권(化權): ${r.star}성 → ${palName(r.idx)}[${ZHI_LIST[r.idx]}]`);
  }
  if (sihuaLocations.sci) {
    const r = sihuaLocations.sci;
    lines.push(`화과(化科): ${r.star}성 → ${palName(r.idx)}[${ZHI_LIST[r.idx]}]`);
  }
  if (sihuaLocations.bad) {
    const r = sihuaLocations.bad;
    lines.push(`화기(化忌): ${r.star}성 → ${palName(r.idx)}[${ZHI_LIST[r.idx]}]`);
  }

  lines.push("");
  lines.push("【대한(大限) 분석】");
  // 大限 시작 나이 = ju값, 역행/순행 결정
  const yangGans = new Set(["甲","丙","戊","庚","壬"]);
  const isYangGan = yangGans.has(yearGan);
  // 양남·음녀 = 순행, 음남·양녀 = 역행
  const isForward = (isYangGan && gender !== "F") || (!isYangGan && gender === "F");
  const dahanStartAge = ju; // 水2局=2세, 木3局=3세, 金4局=4세, 土5局=5세, 火6局=6세
  const ageNow = 2026 - birthY;
  let period = 1;
  let periodStartAge = dahanStartAge;
  while (periodStartAge + 10 <= ageNow) {
    periodStartAge += 10;
    period++;
  }
  const periodEndAge = periodStartAge + 9;
  // 순행: +period-1 궁, 역행: -(period-1) 궁
  const dahanIdx = (mengIdx + (isForward ? (period - 1) : -(period - 1)) + 12) % 12;
  lines.push(`대한 기한(起限): ${dahanStartAge}세 (${JU_NAMES[ju] || ju + "국"} 기준)`);
  lines.push(`행운 방향: ${isForward ? "순행(順行)" : "역행(逆行)"}`);
  lines.push(`현재 대한: 제${period}대한 (${birthY + periodStartAge}년 ~ ${birthY + periodEndAge}년, ${periodStartAge}세~${periodEndAge}세)`);
  lines.push(`현재 대한 궁위: ${palName(dahanIdx)}[${ZHI_LIST[dahanIdx]}]`);
  if (mainStars[dahanIdx].length) lines.push(`대한 주성: ${mainStars[dahanIdx].join("·")}`);
  if (auxStars[dahanIdx].length)  lines.push(`대한 보성: ${auxStars[dahanIdx].join("·")}`);
  if (badStars[dahanIdx].length)  lines.push(`대한 살성: ${badStars[dahanIdx].join("·")}`);

  lines.push("");
  lines.push("【소한(小限) 2026년】");
  // 소한: 양남·음녀 순행, 음남·양녀 역행 (대한과 동일 방향)
  const flowAge = ageNow;
  const flowStep = flowAge % 12;
  let flowIdx;
  if (isForward) {
    flowIdx = (mengIdx + flowStep) % 12;
  } else {
    flowIdx = (mengIdx - flowStep + 12 * 12) % 12;
  }
  lines.push(`2026년 소한 궁위: ${palName(flowIdx)}[${ZHI_LIST[flowIdx]}]`);
  if (mainStars[flowIdx].length) lines.push(`소한 주성: ${mainStars[flowIdx].join("·")}`);
  if (auxStars[flowIdx].length)  lines.push(`소한 보성: ${auxStars[flowIdx].join("·")}`);
  if (badStars[flowIdx].length)  lines.push(`소한 살성: ${badStars[flowIdx].join("·")}`);

  return lines.join("\n");
}


