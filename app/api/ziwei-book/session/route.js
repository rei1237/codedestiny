export async function POST(req) {
  try {
    const body = await req.json().catch(() => ({}));
    const sessionId = Number(body?.sessionId || 0);
    // 생년월일 파라미터 (서버 계산용)
    const birthYear  = Number(body?.birthYear  || 0);
    const birthMonth = Number(body?.birthMonth || 0);
    const birthDay   = Number(body?.birthDay   || 0);
    const birthHour  = (body?.birthHour !== undefined && body?.birthHour !== null) ? Number(body.birthHour) : -1;
    const bodyGender = String(body?.gender || "").trim();
    const bodyName   = String(body?.name   || "사용자").trim();

    // 생년월일 제공 시 서버에서 자미두수 직접 계산 (정확도 우선)
    let ziweiData = String(body?.ziweiData || "").trim();
    if (birthYear >= 1900 && birthMonth >= 1 && birthDay >= 1) {
      const hourForCalc = birthHour >= 0 ? birthHour : 12;
      const calcResult = calcZiweiServer(birthYear, birthMonth, birthDay, hourForCalc);
      if (calcResult) {
        const computed = buildZiweiDataString(
          calcResult, bodyName, bodyGender,
          birthYear, birthMonth, birthDay, birthHour
        );
        if (computed) ziweiData = computed;
      }
    }

    if (sessionId < 1 || sessionId > 13) {
      return NextResponse.json(
        { ok: false, message: "sessionId는 1~12 사이여야 합니다." },
        { status: 400 }
      );
    }
    if (!ziweiData) {
      return NextResponse.json(
        { ok: false, message: "ziweiData가 필요합니다." },
        { status: 400 }
      );
    }

    const config = SESSION_CONFIGS[sessionId - 1];
    const userPrompt = config.prompt(ziweiData);
    const geminiKeys = pickGeminiKeys();
    const vertexKey = pickVertexKey();
    const models = pickZiweiModels();
    let lastError = null;

    // Vertex AI 우선 시도 (고품질·장문 출력 우선)
    if (vertexKey) {
      for (const model of models) {
        const endpoint = VERTEX_ENDPOINT.replace("{model}", encodeURIComponent(model));
        const generationConfig = makeGenerationConfig(model);
        const requestBody = JSON.stringify({
          systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
          contents: [{ role: "user", parts: [{ text: userPrompt }] }],
          generationConfig,
        });

        try {
          const response = await fetch(endpoint, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              "x-goog-api-key": vertexKey,
            },
            body: requestBody,
          });
          const payload = await response.json().catch(() => ({}));

          if (response.ok) {
            const text = parseText(payload);
            const finishReason = getFinishReason(payload);
            if (text && text.length >= 200) {
              return NextResponse.json({
                ok: true,
                text: finishReason === "MAX_TOKENS"
                  ? text + "\n\n---\n> ⚠️ *이 챕터의 내용이 최대 출력 길이에 도달했을 수 있습니다.*"
                  : text,
                sessionId,
                title: config.title,
                emoji: config.emoji,
                model: `vertex/${model}`,
                truncated: finishReason === "MAX_TOKENS",
              });
            }
            lastError = "Vertex AI 응답이 비어 있거나 너무 짧습니다.";
          } else {
            const errMsg = getApiErrorMessage(response.status, payload);
            if (isQuotaError(response.status, errMsg)) { lastError = errMsg; break; }
            lastError = errMsg;
          }
        } catch (fetchErr) {
          lastError = String(fetchErr?.message || "Vertex 네트워크 오류");
        }
      }
    }

    // Gemini 폴백
    for (const model of models) {
      const endpoint = GEMINI_ENDPOINT.replace("{model}", encodeURIComponent(model));
      const generationConfig = makeGenerationConfig(model);
      const requestBody = JSON.stringify({
        systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
        contents: [{ role: "user", parts: [{ text: userPrompt }] }],
        generationConfig,
      });

      for (const apiKey of geminiKeys) {
        try {
          const response = await fetch(`${endpoint}?key=${encodeURIComponent(apiKey)}`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: requestBody,
          });
          const payload = await response.json().catch(() => ({}));

          if (response.ok) {
            const text = parseText(payload);
            const finishReason = getFinishReason(payload);
            if (text && text.length >= 200) {
              return NextResponse.json({
                ok: true,
                text: finishReason === "MAX_TOKENS"
                  ? text + "\n\n---\n> ⚠️ *이 챕터의 내용이 최대 출력 길이에 도달했을 수 있습니다.*"
                  : text,
                sessionId,
                title: config.title,
                emoji: config.emoji,
                model,
                truncated: finishReason === "MAX_TOKENS",
              });
            }
            lastError = "Gemini 응답이 비어 있거나 너무 짧습니다.";
            continue;
          }

          const errMsg = getApiErrorMessage(response.status, payload);
          if (isQuotaError(response.status, errMsg)) {
            lastError = errMsg;
            break;
          }
          lastError = errMsg;
        } catch (fetchErr) {
          lastError = String(fetchErr?.message || "네트워크 오류");
        }
      }
    }

    return NextResponse.json(
      { ok: false, message: lastError || "챕터 생성에 실패했습니다. API 키를 확인해 주세요." },
      { status: 502 }
    );
  } catch (e) {
    return NextResponse.json(
      { ok: false, message: String(e?.message || "요청 처리에 실패했습니다.") },
      { status: 500 }
    );
  }
}
