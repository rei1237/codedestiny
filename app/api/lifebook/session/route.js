export async function POST(req) {
  try {
    const body = await req.json().catch(() => ({}));
    const sessionId = Number(body?.sessionId || 0);
    const sajuData = String(body?.sajuData || "").trim();

    if (sessionId < 1 || sessionId > 10) {
      return NextResponse.json(
        { ok: false, message: "sessionId는 1~10 사이여야 합니다." },
        { status: 400 }
      );
    }
    if (!sajuData) {
      return NextResponse.json(
        { ok: false, message: "sajuData가 필요합니다." },
        { status: 400 }
      );
    }

    const apiKey = getLifeBookKey();
    if (!apiKey) {
      return NextResponse.json(
        { ok: false, message: "인생의 책 전용 API 키(VERTEX_API_KEY)가 설정되지 않았습니다." },
        { status: 500 }
      );
    }

    const config = SESSION_CONFIGS[sessionId - 1];
    const model = String(
      process.env.VERTEX_GEMINI_MODEL ||
      process.env.LIFEBOOK_GEMINI_MODEL ||
      "gemini-2.5-pro"
    ).trim();
    const endpoint = GEMINI_ENDPOINT.replace("{model}", encodeURIComponent(model));
    const userPrompt = config.prompt(sajuData);

    // gemini-2.5 계열 thinking 모델 — thinkingBudget:0 으로 비활성화하여
    // 모든 출력 토큰을 본문 생성에 집중시킴. maxOutputTokens는 넉넉히 65536 설정.
    const isThinkingModel = /gemini-2\.5/.test(model);
    const maxOutputTokens = 65536;
    const generationConfig = { maxOutputTokens, temperature: 1.0 };
    if (isThinkingModel) {
      generationConfig.thinkingConfig = { thinkingBudget: 0 };
    }

    try {
      const response = await fetch(`${endpoint}?key=${encodeURIComponent(apiKey)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
          contents: [{ role: "user", parts: [{ text: userPrompt }] }],
          generationConfig,
        }),
      });

      const payload = await response.json().catch(() => ({}));
      if (!response.ok) {
        const errMsg = payload?.error?.message || `API 요청 실패 (${response.status})`;
        return NextResponse.json(
          { ok: false, message: errMsg },
          { status: 502 }
        );
      }

      const text = parseText(payload);
      const finishReason = getFinishReason(payload);

      if (!text) {
        return NextResponse.json(
          { ok: false, message: "모델 응답이 비어 있습니다." },
          { status: 502 }
        );
      }

      if (finishReason === "MAX_TOKENS") {
        return NextResponse.json({
          ok: true,
          text: text + "\n\n---\n> ⚠️ *이 챕터의 내용이 최대 출력 길이에 도달하여 일부 생략되었을 수 있습니다.*",
          sessionId,
          title: config.title,
          emoji: config.emoji,
          model,
          truncated: true,
        });
      }

      return NextResponse.json({
        ok: true,
        text,
        sessionId,
        title: config.title,
        emoji: config.emoji,
        model,
      });
    } catch (e) {
      return NextResponse.json(
        { ok: false, message: String(e?.message || "챕터 생성에 실패했습니다.") },
        { status: 502 }
      );
    }
  } catch (e) {
    return NextResponse.json(
      { ok: false, message: String(e?.message || "요청 처리에 실패했습니다.") },
      { status: 500 }
    );
  }
}
