function relationByOffset(index: number, offset: number) {
  return ORDER[(index + offset + ORDER.length) % ORDER.length];
}

function animalName(id: AnimalId) {
  return BASE[id].animal_ko;
}

function buildCompatibility(id: AnimalId): AnimalDestinyData["compatibility"] {
  const idx = ORDER.indexOf(id);
  const best = relationByOffset(idx, 1);
  const good = relationByOffset(idx, 2);
  const challenging = relationByOffset(idx, 5);
  const worst = relationByOffset(idx, 6);

  const getCompInfo = (targetId: AnimalId, relation: string) => {
    const scores = {
      best: { total: 98, romance: 95, friend: 99, work: 92 },
      good: { total: 85, romance: 82, friend: 88, work: 84 },
      challenging: { total: 45, romance: 40, friend: 50, work: 42 },
      worst: { total: 15, romance: 10, friend: 20, work: 12 },
    }[relation] || { total: 50, romance: 50, friend: 50, work: 50 };

    const reasons = {
      best: `${animalName(targetId)}와는 리듬이 자연스럽게 맞아 속도와 감정 밸런스가 환상적입니다.`,
      good: `${animalName(targetId)}와는 서로의 부족한 점을 채워주며 긍정적인 시너지를 냅니다.`,
      challenging: `${animalName(targetId)}와는 가치관의 차이가 있어 서로를 이해하는 데 시간이 걸립니다.`,
      worst: `${animalName(targetId)}와는 소통의 방식이 정반대라 오해가 생기기 쉬운 관계입니다.`,
    }[relation];

    return {
      animal_id: targetId,
      reason: reasons,
      compatibility_score: scores.total,
      clash_point: relation === "worst" || relation === "challenging" ? "주로 대화의 타이밍과 우선순위에서 부딪힙니다." : "큰 부딪힘 없이 물 흐르듯 조화로운 관계입니다.",
      conversation_style: "상대방의 의도를 먼저 파악하고 공감하는 부드러운 대화 방식",
      romance_score: scores.romance,
      friend_score: scores.friend,
      work_score: scores.work,
      maintenance_tip: "서로의 다름을 인정하고 고유한 공간을 존중해 줄 때 관계가 깊어집니다.",
    };
  };

  return {
    best: getCompInfo(best, "best"),
    good: getCompInfo(good, "good"),
    challenging: getCompInfo(challenging, "challenging"),
    worst: getCompInfo(worst, "worst"),
  };
}

export const ANIMAL_DESTINY_DATA: Record<AnimalId, AnimalDestinyData> = ORDER.reduce((acc, id) => {
  acc[id] = {
    ...BASE[id],
    compatibility: buildCompatibility(id),
  };
  return acc;
}, {} as Record<AnimalId, AnimalDestinyData>);

export const ANIMAL_DESTINY_LIST: AnimalDestinyData[] = ORDER.map((id) => ANIMAL_DESTINY_DATA[id]);
